#!/usr/bin/env python3
"""File size ratchet: a hand-written source file may not grow past 3,000 lines.

Build plan WS12 S11. A file over the cap needs a ceiling in the committed
baseline, scripts/gates/baselines/file-size.json: the most lines that file may
have. Ceilings only shrink. `--check` fails when a file is over its allowance,
and when a ceiling sits above the file it limits, so the ceiling is lowered in
the same change that shrinks the file. `--update` lowers ceilings and drops the
entries no longer needed; it never raises a ceiling and never adds a file, so a
file that outgrows the cap has to be split. `--init` writes the baseline once.

`--base-ref` reads the baseline and the rule constants (cap, counted suffixes,
generated names and markers, excluded directories) from the base branch and fails
if the change grants more than the base did: a higher cap or ceiling, a suffix no
longer counted, a new exclusion, or a new entry for a file that was under the cap.
A file tracked at the base that the change takes out of the count (for example by
adding a generated marker) fails too. So does a baselined file that git reports as
renamed out of the count: a rename into a generated, excluded or uncounted path is
refused, and a rename to a counted path keeps the old ceiling, which the new path may
not raise. A plain deletion is allowed. A base branch with no baseline yet, the change
that introduces the ratchet, is not compared.

Counted: tracked files with a source suffix, minus generated code (`*.pb.go`,
`*_pb.ts`, anything under a `gen` directory, and a file whose first 40 lines carry
`@generated`, `Code generated`, `DO NOT EDIT` or the OpenAPI Generator banner, which
the SDK regenerates and so must not be pinned to a ceiling), and anything under
`node_modules`, `target` or `dist`. `--ref` counts the committed tree at a git ref
instead of the working tree, so a baseline is never written from uncommitted edits.

Usage, from the repository root:
    python3 scripts/gates/size-ratchet.py --check [--base-ref origin/<branch>]
    python3 scripts/gates/size-ratchet.py --update
    python3 scripts/gates/size-ratchet.py --init --ref <branch>
Exit codes: 0 ok, 1 a file over its allowance, a stale ceiling or a relaxed
baseline, 2 the gate cannot run.
"""
import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BASELINE_REL = 'scripts/gates/baselines/file-size.json'
SCRIPT_REL = 'scripts/gates/size-ratchet.py'
CAP = 3000
SOURCE_SUFFIXES = ('.rs', '.go', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.py', '.sh', '.css', '.sql')
GENERATED_NAMES = ('.pb.go', '_pb.ts')
EXCLUDED_DIRS = {'gen', 'node_modules', 'target', 'dist'}
GENERATED_MARKERS = (b'@generated', b'Code generated', b'DO NOT EDIT', b'Generated by OpenAPI Generator')
HEADER_LINES = 40
BATCH = 200
# The rule constants a change may tighten but not loosen, read from the base branch by --base-ref.
POLICY_NAMES = ('CAP', 'SOURCE_SUFFIXES', 'GENERATED_NAMES', 'EXCLUDED_DIRS', 'GENERATED_MARKERS')


def git(root, *args, stdin=None):
    return subprocess.run(['git', '-C', str(root), *args], input=stdin, stdout=subprocess.PIPE, check=True).stdout


def in_scope(path):
    parts = path.split('/')
    return (path.endswith(SOURCE_SUFFIXES) and not path.endswith(GENERATED_NAMES)
            and not any(part in EXCLUDED_DIRS for part in parts[:-1]))


def tracked_blobs(root, ref):
    """(path, blob) for each tracked file; the blob is None when the working tree is read."""
    if ref is None:
        return [(name, None) for name in git(root, 'ls-files', '-z').decode('utf-8').split('\0') if name]
    blobs = []
    for row in git(root, 'ls-tree', '-r', '-z', '--full-tree', ref).decode('utf-8').split('\0'):
        if row:
            meta, path = row.split('\t', 1)
            mode, kind, blob = meta.split()
            if kind == 'blob' and mode != '120000':
                blobs.append((path, blob))
    return blobs


def contents(root, ref, blobs):
    if ref is None:
        for path, _ in blobs:
            file = root / path
            if file.is_file() and not file.is_symlink():
                yield path, file.read_bytes()
        return
    for start in range(0, len(blobs), BATCH):
        batch = blobs[start:start + BATCH]
        out = git(root, 'cat-file', '--batch', stdin=''.join(f'{blob}\n' for _, blob in batch).encode('utf-8'))
        pos = 0
        for path, _ in batch:
            eol = out.index(b'\n', pos)
            size = int(out[pos:eol].split()[2])
            yield path, out[eol + 1:eol + 1 + size]
            pos = eol + 2 + size


def scan(root, ref=None):
    """Line count of each in-scope tracked file, or None when the file is generated."""
    blobs = [(path, blob) for path, blob in tracked_blobs(root, ref) if in_scope(path)]
    counts = {}
    for path, data in contents(root, ref, blobs):
        lines = data.splitlines()
        generated = any(marker in b'\n'.join(lines[:HEADER_LINES]) for marker in GENERATED_MARKERS)
        counts[path] = None if generated else len(lines)
    return counts


def parse_baseline(text):
    data = json.loads(text)
    if not isinstance(data, dict) or not all(isinstance(v, int) for v in data.values()):
        raise ValueError('the baseline must map each path to an integer ceiling')
    return data


def write_baseline(path, baseline):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(baseline, fh, indent=1, sort_keys=True)
        fh.write('\n')


def violations(counts, baseline):
    """Files over their allowance, and baseline entries that must be lowered or dropped."""
    over, stale = [], []
    for path, lines in sorted(counts.items()):
        if lines is None:
            continue
        if path in baseline and lines > baseline[path]:
            over.append(f'{path}: {lines} lines, over its ceiling of {baseline[path]}')
        elif path not in baseline and lines > CAP:
            over.append(f'{path}: {lines} lines, over the {CAP}-line cap with no ceiling (split the file)')
    for path, ceiling in sorted(baseline.items()):
        lines = counts.get(path)
        if lines is None:
            stale.append(f'{path}: no longer a counted file (deleted, moved or generated); drop its entry')
        elif lines <= CAP:
            stale.append(f'{path}: {lines} lines, within the cap; drop its entry')
        elif lines < ceiling:
            stale.append(f'{path}: {lines} lines, under its ceiling of {ceiling}; lower it')
    return over, stale


def tightened(counts, baseline):
    """What `--update` writes: each kept ceiling lowered to its file's size, never raised."""
    return {path: min(ceiling, counts[path]) for path, ceiling in baseline.items()
            if counts.get(path) is not None and counts[path] > CAP}


def initial(counts):
    return {path: lines for path, lines in counts.items() if lines is not None and lines > CAP}


def policy_at(root, ref):
    """The rule constants as the gate script stands at a git ref, read without running that script."""
    found = {}
    for node in ast.parse(git(root, 'show', f'{ref}:{SCRIPT_REL}').decode('utf-8')).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in POLICY_NAMES:
                found[node.targets[0].id] = ast.literal_eval(node.value)
    if set(found) != set(POLICY_NAMES):
        raise ValueError(f'{SCRIPT_REL} at {ref} must set {", ".join(POLICY_NAMES)} as literals')
    return found


def loosenings(base, head):
    """Rule changes that let more files through: a higher cap, a suffix no longer counted, or a new exclusion."""
    notes = []
    if head['CAP'] > base['CAP']:
        notes.append(f"the cap is raised from {base['CAP']} to {head['CAP']}")
    if not set(base['SOURCE_SUFFIXES']) <= set(head['SOURCE_SUFFIXES']):
        notes.append('a source suffix is no longer counted')
    for name in ('GENERATED_NAMES', 'EXCLUDED_DIRS', 'GENERATED_MARKERS'):
        if not set(head[name]) <= set(base[name]):
            notes.append(f'{name} gains an entry')
    return notes


def relaxations(base_policy, base, head_policy, head, counts, moved):
    """What the change grants beyond the base: looser rules, a higher ceiling, a tracked file taken out of the count, or a baselined file moved out of it."""
    notes = loosenings(base_policy, head_policy)
    came_from = {new: old for old, new in moved.items()}
    for path in sorted(set(base) | set(head)):
        before = base.get(path, base_policy['CAP'])
        if path not in base and path in came_from:
            # A renamed file keeps its ceiling: the new path may carry the old allowance but not raise it.
            before = base.get(came_from[path], before)
        after = head.get(path, head_policy['CAP'])
        if after > before:
            notes.append(f'{path}: allowance raised from {before} to {after}')
    for old, new in sorted(moved.items()):
        if counts.get(new) is None:
            notes.append(f'{old}: renamed to {new}, which is not counted; a baselined file cannot leave the count by moving')
    for path in sorted(base):
        if path in counts and counts[path] is None:
            notes.append(f'{path}: tracked at the base, now excluded from the count as generated')
    return notes


def renamed_out_of_count(root, base_ref, ref, base, counts):
    """Baselined files that git reports as renamed and that the count no longer holds, as {old: new}."""
    gone = [path for path in base if counts.get(path) is None]
    if not gone:
        return {}
    # -M pairs a removed path with an added one; R keeps only those pairs, each three NUL-separated fields.
    args = ['diff', '--name-status', '-z', '-M', '--diff-filter=R', base_ref, *([ref] if ref else []), '--']
    fields = git(root, *args).decode('utf-8').split('\0')
    renamed = {fields[i + 1]: fields[i + 2] for i in range(0, len(fields) - 2, 3)}
    return {old: renamed[old] for old in gone if old in renamed}


def compare_with_base(root, base_ref, baseline, counts, ref=None):
    git(root, 'rev-parse', '--verify', '--quiet', f'{base_ref}^{{commit}}')
    present = subprocess.run(['git', '-C', str(root), 'cat-file', '-e', f'{base_ref}:{BASELINE_REL}'],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0
    if not present:
        print(f'note: {base_ref} has no size baseline yet, so this change is not compared with it')
        return []
    base = parse_baseline(git(root, 'show', f'{base_ref}:{BASELINE_REL}').decode('utf-8'))
    head_policy = {name: globals()[name] for name in POLICY_NAMES}
    moved = renamed_out_of_count(root, base_ref, ref, base, counts)
    return relaxations(policy_at(root, base_ref), base, head_policy, baseline, counts, moved)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='fail on growth, stale ceilings or a relaxed baseline (default)')
    mode.add_argument('--update', action='store_true', help='lower ceilings and drop entries no longer needed; never raises or adds')
    mode.add_argument('--init', action='store_true', help='write the baseline once from the files over the cap')
    ap.add_argument('--ref', help='count the committed tree at this git ref instead of the working tree')
    ap.add_argument('--base-ref', help='also fail if this change grants more than the baseline at this git ref')
    ap.add_argument('--root', type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    root = args.root
    baseline_path = root / BASELINE_REL
    try:
        if args.init:
            if baseline_path.exists():
                print(f'::error::{BASELINE_REL} exists; lower its ceilings with --update')
                return 2
            created = initial(scan(root, args.ref))
            write_baseline(baseline_path, created)
            print(f'baseline written: {len(created)} files over the cap')
            return 0

        if not baseline_path.exists():
            print(f'::error::{BASELINE_REL} is missing; write it once with --init')
            return 2
        baseline = parse_baseline(baseline_path.read_text(encoding='utf-8'))
        counts = scan(root, args.ref)
        if args.update:
            lowered = tightened(counts, baseline)
            write_baseline(baseline_path, lowered)
            print(f'baseline lowered: {len(lowered)} ceilings kept')
            return 0

        over, stale = violations(counts, baseline)
        relaxed = compare_with_base(root, args.base_ref, baseline, counts, args.ref) if args.base_ref else []
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f'::error::size ratchet cannot run: {exc}')
        return 2

    problems = over + stale + relaxed
    if problems:
        print(f'::error::size ratchet: {len(problems)} problem(s)')
        for line in problems[:50]:
            print(f'  {line}')
        if len(problems) > 50:
            print(f'  ... and {len(problems) - 50} more')
        print('split a file that is over its ceiling; after a file shrinks, run --update in the same change')
        return 1
    over_cap = sum(1 for lines in counts.values() if lines is not None and lines > CAP)
    print(f'size ratchet ok: {over_cap} files over the cap, {len(baseline)} ceilings')
    return 0


if __name__ == '__main__':
    sys.exit(main())
