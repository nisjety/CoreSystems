import contextlib
import importlib.util
import io
import json
import pathlib
import subprocess
import tempfile
import unittest
from unittest import mock

SPEC = importlib.util.spec_from_file_location(
    'size_ratchet', pathlib.Path(__file__).resolve().parents[1] / 'gates' / 'size-ratchet.py'
)
gate = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(gate)

GATE_SOURCE = pathlib.Path(gate.__file__).read_text(encoding='utf-8')


def source(n, header=''):
    return header + ''.join(f'// line {i}\n' for i in range(n))


class Repo:
    """A throwaway git repository in which the gate runs with --root."""

    def __init__(self, testcase):
        tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        testcase.addCleanup(tmp.cleanup)
        self.root = pathlib.Path(tmp.name)
        self.git('init', '-q')

    def git(self, *args):
        result = subprocess.run(
            ['git', '-C', str(self.root), '-c', 'user.name=size-ratchet', '-c', 'user.email=size-ratchet@example.invalid', *args],
            check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )
        return result.stdout.decode('utf-8').strip()

    def write(self, rel, text):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')

    def install_gate(self):
        # A base commit must carry the gate script, because the cap is read from it.
        self.write(gate.SCRIPT_REL, GATE_SOURCE)

    def remove(self, rel):
        self.git('rm', '-q', rel)

    def move(self, old, new):
        (self.root / new).parent.mkdir(parents=True, exist_ok=True)
        self.git('mv', old, new)

    def commit(self):
        self.git('add', '-A')
        self.git('commit', '-q', '--allow-empty', '-m', 'change')
        return self.git('rev-parse', 'HEAD')

    def run(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = gate.main(['--root', str(self.root), *argv])
        return code, out.getvalue()

    def baseline(self):
        return json.loads((self.root / gate.BASELINE_REL).read_text(encoding='utf-8'))


class CountTest(unittest.TestCase):
    def test_only_hand_written_source_is_counted(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(10))
        repo.write('docs/notes.md', source(5000))
        repo.write('apps/x/main.pb.go', source(5000))
        repo.write('apps/x/gen/model.rs', source(5000))
        repo.write('web/node_modules/lib.ts', source(5000))
        repo.write('apps/y/schema.ts', source(5000, header='// Code generated by a tool. DO NOT EDIT.\n'))
        repo.write('apps/z/sdk.py', source(5000, header='"""\nGenerated by OpenAPI Generator (https://openapi-generator.tech)\n"""\n'))
        repo.commit()
        # Generated files by marker stay in the scan as None, so a base-ref check can see them leave the count.
        self.assertEqual(gate.scan(repo.root), {'src/a.rs': 10, 'apps/y/schema.ts': None, 'apps/z/sdk.py': None})

    def test_a_marker_below_the_header_does_not_exempt_a_file(self):
        repo = Repo(self)
        repo.write('src/late.rs', source(60) + '// DO NOT EDIT\n')
        repo.commit()
        self.assertEqual(gate.scan(repo.root), {'src/late.rs': 61})

    def test_a_ref_is_counted_rather_than_the_working_tree(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(3100))
        ref = repo.commit()
        repo.write('src/a.rs', source(10))
        self.assertEqual(gate.scan(repo.root, ref), {'src/a.rs': 3100})
        self.assertEqual(gate.scan(repo.root), {'src/a.rs': 10})


class RatchetTest(unittest.TestCase):
    def test_a_file_at_the_cap_passes_and_one_over_it_needs_a_ceiling(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(gate.CAP))
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        self.assertEqual(repo.run('--check')[0], 0)
        repo.write('src/a.rs', source(gate.CAP + 1))
        self.assertEqual(repo.run('--check')[0], 1)
        self.assertEqual(repo.run('--update')[0], 0)
        self.assertEqual(repo.baseline(), {})

    def test_init_records_only_the_files_over_the_cap_and_refuses_to_overwrite(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(3100))
        repo.write('src/b.rs', source(2999))
        repo.commit()
        self.assertEqual(repo.run('--init')[0], 0)
        self.assertEqual(repo.baseline(), {'src/a.rs': 3100})
        self.assertEqual(repo.run('--check')[0], 0)
        self.assertEqual(repo.run('--init')[0], 2)

    def test_growth_past_a_ceiling_fails_and_update_never_raises_it(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        repo.write('src/a.rs', source(3101))
        self.assertEqual(repo.run('--check')[0], 1)
        self.assertEqual(repo.run('--update')[0], 0)
        self.assertEqual(repo.baseline(), {'src/a.rs': 3100})
        self.assertEqual(repo.run('--check')[0], 1)

    def test_a_shrink_must_lower_the_ceiling_in_the_same_change(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        repo.write('src/a.rs', source(3050))
        self.assertEqual(repo.run('--check')[0], 1)
        repo.run('--update')
        self.assertEqual(repo.baseline(), {'src/a.rs': 3050})
        self.assertEqual(repo.run('--check')[0], 0)

    def test_a_file_under_the_cap_or_deleted_loses_its_entry(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(3100))
        repo.write('src/b.rs', source(3200))
        repo.commit()
        repo.run('--init')
        repo.write('src/a.rs', source(2900))
        repo.remove('src/b.rs')
        self.assertEqual(repo.run('--check')[0], 1)
        repo.run('--update')
        self.assertEqual(repo.baseline(), {})
        self.assertEqual(repo.run('--check')[0], 0)

    def test_a_change_that_raises_a_ceiling_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.write(gate.BASELINE_REL, '{"src/a.rs": 3150}\n')
        repo.write('src/a.rs', source(3150))
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('allowance raised from 3100 to 3150', out)

    def test_a_new_entry_for_a_file_under_the_cap_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.write('src/a.rs', source(2900))
        base = repo.commit()
        repo.write('src/a.rs', source(3100))
        repo.write(gate.BASELINE_REL, '{"src/a.rs": 3100}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('allowance raised from 3000 to 3100', out)

    def test_raising_the_cap_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.write('src/a.rs', source(3100))
        base = repo.commit()
        with mock.patch.object(gate, 'CAP', 3500):
            code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('the cap is raised from 3000 to 3500', out)

    def test_a_generated_marker_cannot_take_a_base_file_out_of_the_count(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.write('src/a.rs', source(3100, header='// DO NOT EDIT\n'))
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('now excluded from the count as generated', out)

    def test_excluding_a_directory_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.write('src/a.rs', source(3100))
        base = repo.commit()
        with mock.patch.object(gate, 'EXCLUDED_DIRS', gate.EXCLUDED_DIRS | {'src'}):
            code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('EXCLUDED_DIRS gains an entry', out)

    def test_a_baselined_file_git_mv_ed_into_gen_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'apps/x/gen/a.rs')
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('src/a.rs: renamed to apps/x/gen/a.rs, which is not counted', out)

    def test_a_baselined_file_renamed_to_an_uncounted_suffix_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'src/a.txt')
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('src/a.rs: renamed to src/a.txt, which is not counted', out)

    def test_a_baselined_file_renamed_to_a_generated_file_fails_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'src/b.rs')
        repo.write('src/b.rs', source(3100, header='// DO NOT EDIT\n'))
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('src/a.rs: renamed to src/b.rs, which is not counted', out)

    def test_a_baselined_file_renamed_to_a_counted_path_keeps_its_ceiling(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'src/b.rs')
        repo.write(gate.BASELINE_REL, '{"src/b.rs": 3100}\n')
        repo.commit()
        self.assertEqual(repo.run('--check', '--base-ref', base)[0], 0)

    def test_a_rename_may_not_raise_the_ceiling_it_carries(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'src/b.rs')
        repo.write(gate.BASELINE_REL, '{"src/b.rs": 3150}\n')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('src/b.rs: allowance raised from 3100 to 3150', out)

    def test_a_baselined_file_deleted_outright_passes_against_the_base(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.remove('src/a.rs')
        repo.write(gate.BASELINE_REL, '{}\n')
        repo.commit()
        self.assertEqual(repo.run('--check', '--base-ref', base)[0], 0)

    def test_a_rename_is_found_when_the_tree_is_read_from_a_ref(self):
        repo = Repo(self)
        repo.install_gate()
        repo.write('src/a.rs', source(3100))
        repo.commit()
        repo.run('--init')
        base = repo.commit()
        repo.move('src/a.rs', 'apps/x/gen/a.rs')
        repo.write(gate.BASELINE_REL, '{}\n')
        head = repo.commit()
        code, out = repo.run('--check', '--ref', head, '--base-ref', base)
        self.assertEqual(code, 1)
        self.assertIn('src/a.rs: renamed to apps/x/gen/a.rs, which is not counted', out)

    def test_a_base_without_a_baseline_is_not_compared(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(10))
        base = repo.commit()
        repo.write('src/b.rs', source(3100))
        repo.commit()
        repo.run('--init')
        repo.commit()
        code, out = repo.run('--check', '--base-ref', base)
        self.assertEqual(code, 0)
        self.assertIn('not compared', out)

    def test_a_missing_baseline_or_an_unknown_base_ref_cannot_run(self):
        repo = Repo(self)
        repo.write('src/a.rs', source(10))
        repo.commit()
        self.assertEqual(repo.run('--check')[0], 2)
        repo.write(gate.BASELINE_REL, '{}\n')
        self.assertEqual(repo.run('--check', '--base-ref', 'origin/no-such-branch')[0], 2)


