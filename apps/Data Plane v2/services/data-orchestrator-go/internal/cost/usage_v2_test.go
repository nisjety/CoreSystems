// resignWithHeader re-signs an envelope's token with its header edited, keeping the claims.
func resignWithHeader(t *testing.T, envelope []byte, producer testProducer, edit func(*jwt.Token)) []byte {
	t.Helper()
	var wire map[string]string
	if err := json.Unmarshal(envelope, &wire); err != nil {
		t.Fatalf("envelope: %v", err)
	}
	parsed, _, err := jwt.NewParser().ParseUnverified(strings.TrimPrefix(wire["authorization"], "Bearer "), jwt.MapClaims{})
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	token := jwt.NewWithClaims(jwt.SigningMethodRS256, parsed.Claims)
	token.Header["kid"] = producer.keyID
	edit(token)
	signed, err := token.SignedString(producer.privateKey)
	if err != nil {
		t.Fatalf("sign: %v", err)
	}
	wire["authorization"] = "Bearer " + signed
	out, _ := json.Marshal(wire)
	return out
}
