// v2Spec describes an envelope a test wants signed.
type v2Spec struct {
	producer  testProducer
	feature   string
	eventType string
	org       string
	zdr       bool
	// userID, when set, is put in the claims (a usage event names none).
	userID *string
	jti    string
	// mutate edits the payload after it is built, to make it wrong in one way.
	mutate func(map[string]any)
	// claims edits the claims after they are built.
	claims func(jwt.MapClaims)
}

func validV2Payload(spec v2Spec) map[string]any {
	digest := sha256.Sum256([]byte("calls of " + spec.jti))
	request := hex.EncodeToString(digest[:])
	return map[string]any{
		"schema_version":    2,
		"event_type":        spec.eventType,
		"feature":           spec.feature,
		"model_used":        "gpt-4o-mini-2024-07-18",
		"provider_used":     "azure-openai",
		"count":             3,
		"input_tokens":      1200,
		"output_tokens":     60,
		"cache_read_tokens": 512,
		"cost_basis":        "metered",
		"estimated":         false,
		"request_digest":    request,
		"org_id":            spec.org,
		"zdr":               spec.zdr,
		"idempotency_key":   "usage:" + spec.feature + ":" + request,
	}
}

func signV2(t *testing.T, spec v2Spec) []byte {
	t.Helper()
	if spec.jti == "" {
		spec.jti = fmt.Sprintf("usage-%s-%d", spec.feature, time.Now().UnixNano())
	}
	if spec.org == "" {
		spec.org = "org-a"
	}
	fields := validV2Payload(spec)
	if spec.mutate != nil {
		spec.mutate(fields)
	}
	payload, err := json.Marshal(fields)
	if err != nil {
		t.Fatalf("marshal payload: %v", err)
	}
	digest := sha256.Sum256(payload)
	now := time.Now().UTC()
	claims := jwt.MapClaims{
		"iss":            spec.producer.issuer,
		"sub":            spec.producer.issuer,
		"aud":            eventAudience,
		"principal_type": "service",
		"org_id":         spec.org,
		"scopes":         []string{spec.producer.scope},
		"zdr":            spec.zdr,
		"event_type":     SubjectCostLedger,
		"payload_sha256": hex.EncodeToString(digest[:]),
		"jti":            spec.jti,
		"iat":            now.Unix(),
		"nbf":            now.Unix(),
		"exp":            now.Add(2 * time.Minute).Unix(),
	}
	if spec.userID != nil {
		claims["user_id"] = *spec.userID
	}
	if spec.claims != nil {
		spec.claims(claims)
	}
	token := jwt.NewWithClaims(jwt.SigningMethodRS256, claims)
	token.Header["kid"] = spec.producer.keyID
	signed, err := token.SignedString(spec.producer.privateKey)
	if err != nil {
		t.Fatalf("sign: %v", err)
	}
	wire, err := json.Marshal(map[string]string{
		"authorization": "Bearer " + signed,
		"data":          base64.RawURLEncoding.EncodeToString(payload),
	})
	if err != nil {
		t.Fatalf("marshal envelope: %v", err)
	}
	return wire
}

type testProducers struct {
	embedding, retrieval, graph testProducer
	registry                    *VerifierRegistry
}

var (
	sharedProducersOnce sync.Once
	sharedProducers     testProducers
)

// newTestProducers returns the three producers with a registry of its own (so its replay
// cache is fresh). The RSA keys are made once per run: generating nine of them per subtest
// made this package take half a minute.
func newTestProducers(t *testing.T) testProducers {
	t.Helper()
	sharedProducersOnce.Do(func() {
		sharedProducers = testProducers{
			embedding: newTestProducer(t, embeddingIssuer, embeddingKeyID, embeddingScope),
			retrieval: newTestProducer(t, retrievalIssuer, retrievalKeyID, retrievalScope),
			graph:     newTestProducer(t, graphIssuer, graphKeyID, graphScope),
		}
	})
	p := sharedProducers
	p.registry = newTestRegistryOf(t, p.embedding, p.retrieval, p.graph)
	return p
}

// What each producer may report, and nothing else: the feature is what spend is reported and
// budgeted by, so a producer must not be able to put its spend under another's name.
func TestEachProducerMayReportOnlyItsOwnKinds(t *testing.T) {
	allowed := map[string][][2]string{
		"embedding": {{"embedding", "embedding"}, {"llm", "contextual-retrieval"}},
		"retrieval": {{"rerank", "rerank"}, {"rerank", "web-rerank"}},
		"graph":     {{"llm", "graph-extraction"}, {"llm", "graph-community-summary"}},
	}
	every := [][2]string{
		{"embedding", "embedding"}, {"llm", "contextual-retrieval"}, {"llm", "graph-extraction"},
		{"llm", "graph-community-summary"}, {"rerank", "rerank"}, {"rerank", "web-rerank"},
		// Pairs no producer may use.
		{"llm", "embedding"}, {"embedding", "contextual-retrieval"}, {"rerank", "contextual-retrieval"},
		{"llm", "chat"}, {"llm", ""}, {"", "embedding"}, {"LLM", "graph-extraction"},
	}
	for _, name := range []string{"embedding", "retrieval", "graph"} {
		for _, kind := range every {
			ok := false
			for _, pair := range allowed[name] {
				ok = ok || pair == kind
			}
			t.Run(fmt.Sprintf("%s/%s/%s", name, kind[0], kind[1]), func(t *testing.T) {
				p := newTestProducers(t) // a fresh replay cache per case
				producer := map[string]testProducer{"embedding": p.embedding, "retrieval": p.retrieval, "graph": p.graph}[name]
				_, err := p.registry.Verify(SubjectCostLedger, signV2(t, v2Spec{producer: producer, eventType: kind[0], feature: kind[1]}))
				if (err == nil) != ok {
					t.Fatalf("producer %s reporting %v: accepted=%v, want %v", name, kind, err == nil, ok)
				}
			})
		}
	}
}

