const fixturePath = "../../testdata/usage-envelopes.v2.json"

// loadFixture reads the fixture and its pin. A missing or altered file FAILS the test: a
// contract that cannot be read must never read as one that passed.
func loadFixture(t *testing.T) fixture {
	t.Helper()
	raw, err := os.ReadFile(filepath.FromSlash(fixturePath))
	if err != nil {
		t.Fatalf("the usage envelope fixture is missing: %v", err)
	}
	pin, err := os.ReadFile(filepath.FromSlash(fixturePath + ".sha256"))
	if err != nil {
		t.Fatalf("the usage envelope fixture has no pin: %v", err)
	}
	digest := sha256.Sum256([]byte(strings.ReplaceAll(string(raw), "\r\n", "\n")))
	if got := hex.EncodeToString(digest[:]); got != strings.TrimSpace(string(pin)) {
		t.Fatalf("the usage envelope fixture was changed without its pin: sha256 %s, pinned %s. Never edit a copy: regenerate it in usage-ledger-rs and copy the file and its pin", got, strings.TrimSpace(string(pin)))
	}
	var parsed fixture
	if err := json.Unmarshal(raw, &parsed); err != nil {
		t.Fatalf("parse the fixture: %v", err)
	}
	if parsed.Audience != eventAudience || parsed.Subject != SubjectCostLedger || len(parsed.Cases) < 6 {
		t.Fatalf("the fixture is not the usage envelope contract: %+v", parsed.Audience)
	}
	return parsed
}

// registry builds the real verifier registry from the fixture's public keys and puts its
// clock at signedAt plus offset.
func (f fixture) registry(t *testing.T, offset time.Duration) *VerifierRegistry {
	t.Helper()
	pem := func(name string) []byte {
		producer, ok := f.Producers[name]
		if !ok {
			t.Fatalf("the fixture has no producer %s", name)
		}
		return []byte(producer.PublicKeyPEM)
	}
	registry, err := NewVerifierRegistry(RegistryConfig{
		EmbeddingPublicKeyPEM: pem("embedding-engine-rs"),
		RetrievalPublicKeyPEM: pem("retrieval-engine-rs"),
		GraphPublicKeyPEM:     pem("graph-index-rs"),
	}, 1000)
	if err != nil {
		t.Fatalf("registry from the fixture's keys: %v", err)
	}
	registry.now = func() time.Time { return time.Unix(f.SignedAt, 0).Add(offset) }
	return registry
}

// The fixture's producers carry the issuer, key id and scope this service pins, or the
// fixture and the verifier disagree about who a producer is.
func TestFixtureProducersAreTheOnesTheVerifierPins(t *testing.T) {
	fx := loadFixture(t)
	want := map[string][3]string{
		"embedding-engine-rs": {embeddingIssuer, embeddingKeyID, embeddingScope},
		"retrieval-engine-rs": {retrievalIssuer, retrievalKeyID, retrievalScope},
		"graph-index-rs":      {graphIssuer, graphKeyID, graphScope},
	}
	if len(fx.Producers) != len(want) {
		t.Fatalf("the fixture has %d producers, the verifier pins %d", len(fx.Producers), len(want))
	}
	for name, pinned := range want {
		got := fx.Producers[name]
		if got.Issuer != pinned[0] || got.KeyID != pinned[1] || got.Scope != pinned[2] {
			t.Fatalf("%s: fixture says %s/%s/%s, the verifier pins %v", name, got.Issuer, got.KeyID, got.Scope, pinned)
		}
	}
}

// Every envelope the Rust side signs is verified by the real Go verifier and recorded, through
// the real consumer, with every field in its column.
func TestFixtureEnvelopesAreVerifiedAndRecordedColumnForColumn(t *testing.T) {
	fx := loadFixture(t)
	for _, tc := range fx.Cases {
		t.Run(tc.Name, func(t *testing.T) {
			store := &recordingStore{}
			consumer := NewSignedConsumer(store, nil, fx.registry(t, time.Second))
			if err := consumer.process(context.Background(), []byte(tc.Envelope)); err != nil {
				t.Fatalf("a real envelope from the producer was refused: %v", err)
			}
			if len(store.calls) != 1 {
				t.Fatalf("recorded %d rows, want 1", len(store.calls))
			}
			row, want := store.calls[0], tc.Expect
			checks := []struct {
				column string
				got    any
				want   any
			}{
				{"event_type", row[colEventType], want.EventType},
				{"model", row[colModel], want.ModelUsed},
				{"org_id", row[colOrgID], want.OrgID},
				{"user_id", row[colUserID], nil},
				{"count", row[colCount], want.Count},
				{"estimated_tokens", row[colEstimatedTokens], want.InputTokens + want.OutputTokens},
				{"idempotency_key", row[colIdempotencyKey], want.OrgID + ":" + want.IdempotencyKey},
				{"schema_version", row[colSchemaVersion], 2},
				{"feature", row[colFeature], want.Feature},
				{"provider_used", row[colProviderUsed], want.ProviderUsed},
				{"input_tokens", row[colInputTokens], want.InputTokens},
				{"output_tokens", row[colOutputTokens], want.OutputTokens},
				{"cache_read_tokens", row[colCacheReadTokens], want.CacheReadTokens},
				{"cost_basis", row[colCostBasis], want.CostBasis},
				{"estimated", row[colEstimated], want.Estimated},
				{"zdr", row[colZDR], want.ZDR},
				{"request_id", row[colRequestID], want.RequestDigest},
			}
			for _, check := range checks {
				if check.got != check.want {
					t.Errorf("column %s = %#v, want %#v", check.column, check.got, check.want)
				}
			}
			switch {
			case want.Units == nil && row[colUnits] != nil:
				t.Errorf("units = %#v, want NULL", row[colUnits])
			case want.Units != nil && row[colUnits] != *want.Units:
				t.Errorf("units = %#v, want %d", row[colUnits], *want.Units)
			}
		})
	}
}

// The failure the durable consumer exists for. An envelope lives two minutes and waits in the
// stream for as long as the consumer is down, so it is expired when it is read. A live read
// refuses it; the durable read accepts it, as authentic and Stale, for as long as the stream
// keeps it, and never after.
func TestAnAuthenticEnvelopeThatWaitedInTheStreamIsAcceptedOnlyThroughTheDurableDoor(t *testing.T) {
	fx := loadFixture(t)
	tc := fx.Cases[0]
	envelope := []byte(tc.Envelope)

	for _, tt := range []struct {
		name        string
		age         time.Duration
		live        bool // Verify accepts
		durable     bool // VerifyDurable accepts
		durableOnly bool // and reports Stale
	}{
		{name: "fresh", age: time.Second, live: true, durable: true},
		{name: "inside the skew after expiry", age: 2*time.Minute + 20*time.Second, live: true, durable: true},
		{name: "ten minutes", age: 10 * time.Minute, live: false, durable: true, durableOnly: true},
		{name: "a weekend down", age: 60 * time.Hour, live: false, durable: true, durableOnly: true},
		{name: "the stream's oldest message", age: streamMaxAge, live: false, durable: true, durableOnly: true},
		{name: "past what the stream keeps", age: maxBacklogAge + 5*time.Minute, live: false, durable: false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := fx.registry(t, tt.age).Verify(SubjectCostLedger, envelope); (err == nil) != tt.live {
				t.Errorf("live verify err=%v, want accepted=%v", err, tt.live)
			}
			verified, err := fx.registry(t, tt.age).VerifyDurable(SubjectCostLedger, envelope)
			if (err == nil) != tt.durable {
				t.Fatalf("durable verify err=%v, want accepted=%v", err, tt.durable)
			}
			if err == nil && verified.Stale != tt.durableOnly {
				t.Errorf("stale = %v, want %v", verified.Stale, tt.durableOnly)
			}
		})
	}
}

// Relaxing time must relax nothing else. A forged, altered or mis-signed envelope is refused
// through the durable door exactly as through the live one, however old.
func TestTheDurableDoorStillRefusesWhatIsNotAuthentic(t *testing.T) {
	fx := loadFixture(t)
	tc := fx.Cases[0]
	var wire struct {
		Authorization string `json:"authorization"`
		Data          string `json:"data"`
	}
	if err := json.Unmarshal([]byte(tc.Envelope), &wire); err != nil {
		t.Fatalf("envelope: %v", err)
	}
	payload, err := base64.RawURLEncoding.DecodeString(wire.Data)
	if err != nil {
		t.Fatalf("payload: %v", err)
	}
	repackage := func(token string, data []byte) []byte {
		out, _ := json.Marshal(map[string]string{"authorization": token, "data": base64.RawURLEncoding.EncodeToString(data)})
		return out
	}
	parts := strings.Split(strings.TrimPrefix(wire.Authorization, "Bearer "), ".")
	if len(parts) != 3 {
		t.Fatalf("token has %d parts", len(parts))
	}
	flip := func(s string) string {
		b := []byte(s)
		if b[len(b)/2] == 'A' {
			b[len(b)/2] = 'B'
		} else {
			b[len(b)/2] = 'A'
		}
		return string(b)
	}

	for name, envelope := range map[string][]byte{
		"payload changed after signing": repackage(wire.Authorization, []byte(strings.Replace(string(payload), `"org_id":"org-fixture-a"`, `"org_id":"org-fixture-b"`, 1))),
		"signature altered":             repackage("Bearer "+parts[0]+"."+parts[1]+"."+flip(parts[2]), payload),
		"claims altered":                repackage("Bearer "+parts[0]+"."+flip(parts[1])+"."+parts[2], payload),
		"header altered":                repackage("Bearer "+flip(parts[0])+"."+parts[1]+"."+parts[2], payload),
		"no signature":                  repackage("Bearer "+parts[0]+"."+parts[1]+".", payload),
		"not an envelope":               []byte(`{"event_type":"llm"}`),
		"empty":                         {},
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := fx.registry(t, 30*time.Minute).VerifyDurable(SubjectCostLedger, envelope); err == nil {
				t.Fatal("an envelope that is not authentic was accepted through the durable door")
			}
		})
	}

	// Signed by the right producer's key only: the same envelope under a registry holding
	// other keys is nobody's.
	other := newTestProducer(t, embeddingIssuer, embeddingKeyID, embeddingScope)
	otherRetrieval := newTestProducer(t, retrievalIssuer, retrievalKeyID, retrievalScope)
	otherGraph := newTestProducer(t, graphIssuer, graphKeyID, graphScope)
	registry := newTestRegistryOf(t, other, otherRetrieval, otherGraph)
	registry.now = func() time.Time { return time.Unix(fx.SignedAt, 0).Add(30 * time.Minute) }
	if _, err := registry.VerifyDurable(SubjectCostLedger, []byte(tc.Envelope)); err == nil {
		t.Fatal("an envelope signed by another key was accepted")
	}
}

// An authentic envelope is delivered more than once by the broker when an acknowledgement is
// lost. A live one is a replay the second time. A stale one is not remembered (the cache
// forgets at expiry): its duplicate is accepted and is harmless because the row's key is
// unique, which the real-database test below proves.
func TestReplayOfALiveEnvelopeIsRefusedAndOfAStaleOneIsLeftToTheUniqueKey(t *testing.T) {
	fx := loadFixture(t)
	envelope := []byte(fx.Cases[1].Envelope)

	live := fx.registry(t, time.Second)
	if _, err := live.VerifyDurable(SubjectCostLedger, envelope); err != nil {
		t.Fatalf("first delivery: %v", err)
	}
	if _, err := live.VerifyDurable(SubjectCostLedger, envelope); !errors.Is(err, errReplay) {
		t.Fatalf("second delivery of a live envelope: err=%v, want a replay", err)
	}

	stale := fx.registry(t, 20*time.Minute)
	for i := 1; i <= 2; i++ {
		if _, err := stale.VerifyDurable(SubjectCostLedger, envelope); err != nil {
			t.Fatalf("delivery %d of a stale envelope: %v", i, err)
		}
	}
	if len(stale.replay) != 0 {
		t.Fatalf("a stale envelope was entered in the replay cache (%d entries): it would crowd out live ones for nothing", len(stale.replay))
	}
}

