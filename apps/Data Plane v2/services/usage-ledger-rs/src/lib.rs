//! The Data Plane usage ledger, schema_version 2.
//!
//! Every Data Plane service that pays a provider for a call on an organization's behalf
//! (embedding, contextual retrieval, graph extraction, rerank) records what it paid for
//! through this crate, so there is one definition of what an event contains, one rule for
//! how a provider's answer becomes numbers, one place where the event is signed and one
//! stream it is published to.
//!
//! * [`CallUsage`] is one provider call as a producer saw it. [`CallUsage::from_wire`]
//!   copies the usage fields of an inference-core `InferResponse` exactly; a response
//!   served from inference-core's cache is not metered.
//! * [`UsageBuilder`] aggregates the calls of one organization's batch into
//!   [`UsageEvent`]s, with a deterministic idempotency key that contains no document id.
//! * [`LedgerSink`] publishes them: [`JetStreamLedger`] signs with the producer's event
//!   key and waits for the broker's acknowledgement on the durable `DATAPLANE_COST`
//!   stream; [`MemoryLedger`] is the in-memory sink for tests.
//!
//! The consumer is `data-orchestrator-go` (`internal/cost`): it verifies the signature,
//! records the event in `cost_events`, and forwards it to cost-core. The contract between
//! the two is a signed-envelope fixture generated by this crate
//! (`tests/fixtures/usage-envelopes.v2.json`) and read by the Go tests, pinned by sha256 on
//! both sides.
//!
//! Zero-retention organizations are metered too. The event holds counters only (no
//! document, no text, no user), which is what makes that possible; the earlier convention
//! of dropping those events made a zero-retention organization's spend invisible.

