#[tokio::test]
async fn a_quarry_token_with_data_rerank_reaches_the_handler_and_is_metered_once() {
    let h = harness(Opts::default()).await;
    let docs = documents(10);
    let token = service_token(&["data:rerank"]);
    let (status, body) = post(
        &h.base,
        Some(&token),
        &request("rr-admit-0001", &docs),
        None,
    )
    .await;

    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body["status"], "ok", "{body}");
    assert_eq!(h.provider.call_count(), 1, "one provider call per request");
    let calls = h.provider.calls();
    assert_eq!(calls[0].query, "how often should solar panels be cleaned");
    assert!(
        calls[0].api_key_header,
        "the provider receives the api-key header"
    );
    assert_eq!(
        calls[0].documents.len(),
        10,
        "every candidate is sent once, no sharding"
    );
    assert_eq!(calls[0].top_n, 10, "top_n defaults to the document count");

    let costs = decoded_costs(&h.ledger);
    assert_eq!(costs.len(), 1, "one signed cost event");
    let event = &costs[0];
    // The usage ledger's schema_version 2 event under its own feature (QB-M): the web route is
    // metered apart from the tenant rerank, and its field set is the CR-T10 golden's.
    assert_eq!(event["schema_version"], 2, "{event}");
    assert_eq!(event["event_type"], "rerank");
    assert_eq!(event["feature"], "web-rerank");
    assert_eq!(event["model_used"], MODEL);
    assert_eq!(event["provider_used"], PROVIDER_USED);
    assert_eq!(event["count"], 10, "the candidates scored");
    assert_eq!(
        (
            event["input_tokens"].as_i64(),
            event["output_tokens"].as_i64(),
            event["cache_read_tokens"].as_i64(),
        ),
        (Some(0), Some(0), Some(0)),
        "a reranker bills search units, not tokens"
    );
    assert_eq!(event["units"], 1, "the provider's billed search units");
    assert_eq!(event["cost_basis"], "metered");
    assert_eq!(event["estimated"], false);
    assert_eq!(event["org_id"], golden_org());
    assert_eq!(event["zdr"], false);
    assert!(
        event.get("user_id").is_none(),
        "service events carry no user"
    );
    let digest = event["request_digest"].as_str().expect("digest");
    assert_eq!(digest.len(), 64, "sha256 of the call's deterministic key");
    assert!(
        digest
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
        "lowercase hex"
    );
    assert_eq!(
        event["idempotency_key"],
        format!("usage:web-rerank:{digest}"),
        "the verifier's key for a usage event is its feature and its digest"
    );
    assert_eq!(
        cost_message_ids(&h.ledger),
        vec![format!("{}:usage:web-rerank:{digest}", golden_org())],
        "the broker de-duplicates a publish on the organization and the ledger key"
    );
}

/// A cost publish the broker refuses does not change the answer of a call the provider already
/// served: the body is ok, the call is cached (so a replay does not pay again), and nothing is
/// recorded for the refused event.
#[tokio::test]
async fn a_refused_cost_publish_never_changes_the_answer_of_a_call_already_served() {
    let h = harness(Opts::default()).await;
    h.ledger.refuse_next(1);
    let token = service_token(&["data:rerank"]);
    let req = request("rr-refused-0001", &documents(4));
    let (status, body) = post(&h.base, Some(&token), &req, None).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body["status"], "ok", "{body}");
    assert!(
        decoded_costs(&h.ledger).is_empty(),
        "the refused event is not recorded"
    );
    let (_, replay) = post(&h.base, Some(&token), &req, None).await;
    assert_eq!(replay, body, "the replay is served from the cache");
    assert_eq!(h.provider.call_count(), 1, "and the provider is paid once");
}

