// ───────────────────────── wire goldens for Quarry ─────────────────────────

fn golden_path(name: &str) -> String {
    format!("{FIXTURES}/{CONTRACT_DIR}/{name}")
}

fn normalised(bytes: &[u8]) -> Vec<u8> {
    bytes.iter().copied().filter(|b| *b != b'\r').collect()
}

fn check_or_write_golden(name: &str, body: &Value) {
    let rendered = format!("{}\n", serde_json::to_string_pretty(body).expect("json"));
    let path = golden_path(name);
    if std::env::var("UPDATE_CONTRACT_GOLDEN").as_deref() == Ok("1") {
        std::fs::create_dir_all(format!("{FIXTURES}/{CONTRACT_DIR}")).expect("dir");
        std::fs::write(&path, rendered.as_bytes()).expect("write golden");
        return;
    }
    let committed = std::fs::read(&path).unwrap_or_else(|error| {
        panic!("golden {path} is missing ({error}); regenerate with UPDATE_CONTRACT_GOLDEN=1")
    });
    assert_eq!(
        String::from_utf8_lossy(&normalised(&committed)),
        rendered,
        "{name} drifted from the committed wire golden"
    );
}

#[tokio::test]
async fn the_wire_shapes_match_their_committed_goldens() {
    let h = harness(Opts::default()).await;
    let token = service_token(&["data:rerank"]);
    let docs = documents(3);

    let (_, ok) = post(
        &h.base,
        Some(&token),
        &request("rr-golden-ok1", &docs),
        None,
    )
    .await;
    check_or_write_golden("ok.golden.json", &ok);

    let mut zdr = request("rr-golden-zdr1", &docs);
    zdr["zdr_mode"] = json!("ephemeral");
    let (_, skipped) = post(&h.base, Some(&token), &zdr, None).await;
    check_or_write_golden("skipped-zdr.golden.json", &skipped);

    h.provider.queue(Reply::scored().delayed(3_000));
    let mut slow = request("rr-golden-slow", &docs);
    slow["deadline_ms"] = json!(300);
    let (_, degraded) = post(&h.base, Some(&token), &slow, None).await;
    check_or_write_golden("degraded-timeout.golden.json", &degraded);

    if std::env::var("UPDATE_CONTRACT_GOLDEN").as_deref() == Ok("1") {
        let mut sums = String::new();
        for name in [
            "ok.golden.json",
            "skipped-zdr.golden.json",
            "degraded-timeout.golden.json",
        ] {
            let bytes = std::fs::read(golden_path(name)).expect("golden");
            sums.push_str(&format!(
                "{:x}  {name}\n",
                Sha256::digest(normalised(&bytes))
            ));
        }
        std::fs::write(golden_path("SHA256SUMS"), sums).expect("sums");
    } else {
        // The pin is what Quarry's vendored copy is checked against, so it is verified too.
        let sums =
            std::fs::read_to_string(golden_path("SHA256SUMS")).expect("SHA256SUMS is committed");
        let mut pinned = 0;
        for line in sums.lines().filter(|line| !line.trim().is_empty()) {
            let (expected, name) = line.split_once("  ").expect("sha256sum line format");
            let bytes = std::fs::read(golden_path(name)).expect("golden listed in SHA256SUMS");
            assert_eq!(
                format!("{:x}", Sha256::digest(normalised(&bytes))),
                expected,
                "{name} no longer matches its sha256 pin"
            );
            pinned += 1;
        }
        assert_eq!(pinned, 3, "every wire golden is pinned");
    }
}

