#[derive(Clone)]
struct Reply {
    delay_ms: u64,
    status: u16,
    retry_after: Option<u64>,
    location: Option<String>,
    body: Option<Value>,
    search_units: Option<u64>,
}

impl Reply {
    fn scored() -> Self {
        Self {
            delay_ms: 0,
            status: 200,
            retry_after: None,
            location: None,
            body: None,
            search_units: Some(1),
        }
    }

    fn status(status: u16) -> Self {
        Self {
            status,
            body: Some(json!({"message": DOC_MARKER})),
            ..Self::scored()
        }
    }

    fn with_body(body: Value) -> Self {
        Self {
            body: Some(body),
            ..Self::scored()
        }
    }

    fn delayed(mut self, ms: u64) -> Self {
        self.delay_ms = ms;
        self
    }

    fn retry_after(mut self, seconds: u64) -> Self {
        self.retry_after = Some(seconds);
        self
    }

    fn redirect_to(mut self, location: &str) -> Self {
        self.location = Some(location.to_owned());
        self
    }

    fn units(mut self, units: Option<u64>) -> Self {
        self.search_units = units;
        self
    }
}

#[derive(Clone, Debug)]
struct ProviderCall {
    documents: Vec<String>,
    query: String,
    top_n: u64,
    api_key_header: bool,
}

#[derive(Default)]
struct ProviderState {
    calls: Mutex<Vec<ProviderCall>>,
    replies: Mutex<VecDeque<Reply>>,
}

struct Provider {
    addr: SocketAddr,
    state: Arc<ProviderState>,
}

impl Provider {
    fn calls(&self) -> Vec<ProviderCall> {
        self.state.calls.lock().expect("calls").clone()
    }

    fn call_count(&self) -> usize {
        self.calls().len()
    }

    fn queue(&self, reply: Reply) {
        self.state.replies.lock().expect("replies").push_back(reply);
    }
}

fn scored_body(documents: &[String], units: Option<u64>) -> Value {
    let results: Vec<Value> = (0..documents.len())
        .map(|index| json!({"index": index, "relevance_score": 1.0 - (index as f64) * 0.01}))
        .collect();
    let mut body = json!({"results": results});
    if let Some(units) = units {
        body["meta"] = json!({"billed_units": {"search_units": units}});
    }
    body
}

/// The stand-in's certificate, generated once per test process and shared by every harness.
fn provider_certificate() -> &'static (Vec<u8>, Vec<u8>) {
    static CERTIFICATE: OnceLock<(Vec<u8>, Vec<u8>)> = OnceLock::new();
    CERTIFICATE.get_or_init(|| self_signed(PROVIDER_HOST))
}

async fn start_provider() -> Provider {
    let (certificate_der, key_der) = provider_certificate();
    let certificate = rustls::pki_types::CertificateDer::from(certificate_der.clone());
    let key: rustls::pki_types::PrivateKeyDer<'static> =
        rustls::pki_types::PrivatePkcs8KeyDer::from(key_der.clone()).into();
    let config = rustls::ServerConfig::builder_with_provider(Arc::new(
        rustls::crypto::aws_lc_rs::default_provider(),
    ))
    .with_safe_default_protocol_versions()
    .expect("protocol versions")
    .with_no_client_auth()
    .with_single_cert(vec![certificate], key)
    .expect("server certificate");
    let acceptor = tokio_rustls::TlsAcceptor::from(Arc::new(config));
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind provider stand-in");
    let addr = listener.local_addr().expect("addr");
    let state = Arc::new(ProviderState::default());
    let served = state.clone();
    tokio::spawn(async move {
        loop {
            let Ok((socket, _)) = listener.accept().await else {
                return;
            };
            let acceptor = acceptor.clone();
            let state = served.clone();
            tokio::spawn(async move {
                if let Ok(tls) = acceptor.accept(socket).await {
                    handle_connection(tls, state).await;
                }
            });
        }
    });
    Provider { addr, state }
}

async fn handle_connection(
    mut tls: tokio_rustls::server::TlsStream<tokio::net::TcpStream>,
    state: Arc<ProviderState>,
) {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    let mut buffer = Vec::new();
    let head_end = loop {
        if let Some(position) = buffer.windows(4).position(|w| w == b"\r\n\r\n") {
            break position + 4;
        }
        let mut chunk = [0u8; 4096];
        match tls.read(&mut chunk).await {
            Ok(0) | Err(_) => return,
            Ok(read) => buffer.extend_from_slice(&chunk[..read]),
        }
    };
    let head = String::from_utf8_lossy(&buffer[..head_end]).to_ascii_lowercase();
    let content_length = head
        .lines()
        .find_map(|line| line.strip_prefix("content-length:"))
        .and_then(|value| value.trim().parse::<usize>().ok())
        .unwrap_or(0);
    let api_key_header = head.lines().any(|line| line.starts_with("api-key:"));
    while buffer.len() < head_end + content_length {
        let mut chunk = [0u8; 4096];
        match tls.read(&mut chunk).await {
            Ok(0) | Err(_) => return,
            Ok(read) => buffer.extend_from_slice(&chunk[..read]),
        }
    }
    let request: Value =
        serde_json::from_slice(&buffer[head_end..head_end + content_length]).unwrap_or(Value::Null);
    let documents: Vec<String> = request["documents"]
        .as_array()
        .map(|items| {
            items
                .iter()
                .map(|item| item.as_str().unwrap_or_default().to_owned())
                .collect()
        })
        .unwrap_or_default();
    state.calls.lock().expect("calls").push(ProviderCall {
        documents: documents.clone(),
        query: request["query"].as_str().unwrap_or_default().to_owned(),
        top_n: request["top_n"].as_u64().unwrap_or_default(),
        api_key_header,
    });

    let reply = state
        .replies
        .lock()
        .expect("replies")
        .pop_front()
        .unwrap_or_else(Reply::scored);
    if reply.delay_ms > 0 {
        tokio::time::sleep(Duration::from_millis(reply.delay_ms)).await;
    }
    let body = reply
        .body
        .unwrap_or_else(|| scored_body(&documents, reply.search_units));
    let payload = serde_json::to_vec(&body).expect("body");
    let reason = match reply.status {
        200 => "OK",
        429 => "Too Many Requests",
        502 => "Bad Gateway",
        _ => "Error",
    };
    let mut head = format!(
        "HTTP/1.1 {} {}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n",
        reply.status,
        reason,
        payload.len()
    );
    if let Some(seconds) = reply.retry_after {
        head.push_str(&format!("Retry-After: {seconds}\r\n"));
    }
    if let Some(location) = &reply.location {
        head.push_str(&format!("Location: {location}\r\n"));
    }
    head.push_str("\r\n");
    let _ = tls.write_all(head.as_bytes()).await;
    let _ = tls.write_all(&payload).await;
    let _ = tls.shutdown().await;
}

