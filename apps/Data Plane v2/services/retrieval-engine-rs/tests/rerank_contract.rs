fn der_len(len: usize) -> Vec<u8> {
    if len < 128 {
        return vec![len as u8];
    }
    let bytes: Vec<u8> = len
        .to_be_bytes()
        .iter()
        .copied()
        .skip_while(|b| *b == 0)
        .collect();
    let mut out = vec![0x80 | bytes.len() as u8];
    out.extend(bytes);
    out
}

fn tlv(tag: u8, content: &[u8]) -> Vec<u8> {
    let mut out = vec![tag];
    out.extend(der_len(content.len()));
    out.extend_from_slice(content);
    out
}

fn seq(parts: &[Vec<u8>]) -> Vec<u8> {
    tlv(0x30, &parts.concat())
}

fn der_integer_unsigned(bytes: &[u8]) -> Vec<u8> {
    let trimmed: Vec<u8> = bytes.iter().copied().skip_while(|b| *b == 0).collect();
    let mut content = Vec::new();
    if trimmed.first().is_none_or(|b| b & 0x80 != 0) {
        content.push(0);
    }
    content.extend(trimmed);
    tlv(0x02, &content)
}

/// A self-signed X.509 certificate for `host`, built from DER at test time so no private key
/// is committed to the repository. The key is an RSA-2048 key generated per process.
fn self_signed(host: &str) -> (Vec<u8>, Vec<u8>) {
    const OID_SHA256_RSA: &[u8] = &[0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x0b];
    const OID_RSA_ENCRYPTION: &[u8] = &[0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x01];
    const OID_COMMON_NAME: &[u8] = &[0x55, 0x04, 0x03];
    const OID_SUBJECT_ALT_NAME: &[u8] = &[0x55, 0x1d, 0x11];

    let private = RsaPrivateKey::new(&mut rand::thread_rng(), 2048).expect("tls key");
    let pkcs8 = private.to_pkcs8_der().expect("pkcs8").as_bytes().to_vec();
    let public = RsaPublicKey::from(&private);
    let rsa_public = seq(&[
        der_integer_unsigned(&public.n().to_bytes_be()),
        der_integer_unsigned(&public.e().to_bytes_be()),
    ]);
    let mut bit_string = vec![0u8];
    bit_string.extend(rsa_public);
    let spki = seq(&[
        seq(&[tlv(0x06, OID_RSA_ENCRYPTION), tlv(0x05, &[])]),
        tlv(0x03, &bit_string),
    ]);
    let algorithm = seq(&[tlv(0x06, OID_SHA256_RSA), tlv(0x05, &[])]);
    let name = seq(&[tlv(
        0x31,
        &seq(&[tlv(0x06, OID_COMMON_NAME), tlv(0x0c, host.as_bytes())]),
    )]);
    let validity = seq(&[tlv(0x17, b"250101000000Z"), tlv(0x18, b"20991231000000Z")]);
    let san = seq(&[
        tlv(0x06, OID_SUBJECT_ALT_NAME),
        tlv(0x04, &seq(&[tlv(0x82, host.as_bytes())])),
    ]);
    let extensions = tlv(0xa3, &seq(&[san]));
    let tbs = seq(&[
        tlv(0xa0, &der_integer_unsigned(&[2])),
        der_integer_unsigned(&[1]),
        algorithm.clone(),
        name.clone(),
        validity,
        name,
        spki,
        extensions,
    ]);
    let signature = SigningKey::<Sha256>::new(private).sign(&tbs).to_bytes();
    let mut signature_bits = vec![0u8];
    signature_bits.extend_from_slice(&signature);
    let certificate = seq(&[tbs, algorithm, tlv(0x03, &signature_bits)]);
    (certificate, pkcs8)
}

