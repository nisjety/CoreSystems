/// The limit is decided from the declared length, before any body byte is read. The client
/// therefore sends only the headers and reads the status line from the raw socket; a
/// full-body client would race the server's close and never see the status.
#[tokio::test]
async fn a_body_over_one_mebibyte_is_refused_with_413() {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    let h = harness(Opts::default()).await;
    let token = service_token(&["data:rerank"]);
    let length = 1_200_000usize;
    let head = format!(
        "POST /v1/rerank HTTP/1.1\r\nHost: rerank.test\r\nAuthorization: Bearer {token}\r\nContent-Type: application/json\r\nContent-Length: {length}\r\nConnection: close\r\n\r\n"
    );
    let address = h.base.trim_start_matches("http://").to_owned();
    let mut socket = tokio::net::TcpStream::connect(&address)
        .await
        .expect("connect");
    socket
        .write_all(head.as_bytes())
        .await
        .expect("send headers");
    let mut reply = Vec::new();
    loop {
        let mut chunk = [0u8; 1024];
        let read = tokio::time::timeout(Duration::from_secs(5), socket.read(&mut chunk))
            .await
            .expect("the refusal arrives without the body")
            .expect("read");
        assert!(read > 0, "the server closed before answering");
        reply.extend_from_slice(&chunk[..read]);
        if reply.windows(4).any(|w| w == b"\r\n\r\n") {
            break;
        }
    }
    let status_line = String::from_utf8_lossy(&reply)
        .lines()
        .next()
        .unwrap_or_default()
        .to_owned();
    assert!(status_line.starts_with("HTTP/1.1 413"), "{status_line}");
    assert_eq!(h.provider.call_count(), 0);
}

