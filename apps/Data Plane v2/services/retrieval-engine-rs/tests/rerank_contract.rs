// ───────────────────────── log and error hygiene ─────────────────────────

#[derive(Clone, Default)]
struct LogSink(Arc<Mutex<Vec<u8>>>);

impl std::io::Write for LogSink {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.lock().expect("log").extend_from_slice(buf);
        Ok(buf.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

#[tokio::test(flavor = "current_thread")]
async fn no_query_or_document_text_reaches_a_log_line_or_an_error_body() {
    let sink = LogSink::default();
    let subscriber = tracing_subscriber::fmt()
        .with_max_level(tracing::Level::TRACE)
        .with_ansi(false)
        .with_writer({
            let sink = sink.clone();
            move || sink.clone()
        })
        .finish();
    let _guard = tracing::subscriber::set_default(subscriber);

    let h = harness(Opts::default()).await;
    let token = service_token(&["data:rerank"]);
    let mut text_body = request("rr-log-000001", &documents(3));
    text_body["query"] = json!(QUERY_MARKER);
    text_body["documents"][1]["text"] = json!(DOC_MARKER);
    h.provider.queue(Reply::status(502));
    let (_, degraded) = post(&h.base, Some(&token), &text_body, None).await;
    h.provider.queue(Reply::status(429).retry_after(9));
    let mut slow = text_body.clone();
    slow["request_id"] = json!("rr-log-000002");
    slow["deadline_ms"] = json!(500);
    let (_, rate_limited) = post(&h.base, Some(&token), &slow, None).await;
    let (_, refused) = post(
        &h.base,
        Some(&token),
        &{
            let mut bad = text_body.clone();
            bad["request_id"] = json!("x");
            bad
        },
        None,
    )
    .await;

    let logs = String::from_utf8_lossy(&sink.0.lock().expect("log")).to_string();
    for marker in [QUERY_MARKER, DOC_MARKER] {
        assert!(!logs.contains(marker), "{marker} reached a log line");
        assert!(!degraded.to_string().contains(marker));
        assert!(!rate_limited.to_string().contains(marker));
        assert!(!refused.to_string().contains(marker));
    }
}

