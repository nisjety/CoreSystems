/// The usage ledger's sink without a broker. Each event is signed the way `JetStreamLedger` signs
/// it (`UsageEvent::sign` with the producer's key) and recorded under the broker's de-duplication
/// id, so the tests read exactly the envelopes production would publish, and verify them with the
/// real verifier.
struct RecordingLedger {
    signer: EventSigner,
    messages: Mutex<Vec<(String, Vec<u8>)>>,
    refusals: Mutex<usize>,
    /// How long a publish takes to be acknowledged (a slow broker).
    delay: Mutex<Duration>,
}

impl RecordingLedger {
    fn new() -> Self {
        let signer = EventSigner::from_rsa_pem(
            &keys().event_signing_pem,
            "service:retrieval-engine-rs",
            "retrieval-events-v1",
            EVENT_AUDIENCE,
            "events:retrieval:publish",
        )
        .expect("signer");
        Self {
            signer,
            messages: Mutex::new(Vec::new()),
            refusals: Mutex::new(0),
            delay: Mutex::new(Duration::ZERO),
        }
    }

    /// Refuse the next `count` publishes, as a broker that did not acknowledge them would.
    fn refuse_next(&self, count: usize) {
        *self.refusals.lock().expect("refusals") = count;
    }

    fn set_delay(&self, delay: Duration) {
        *self.delay.lock().expect("delay") = delay;
    }
}

impl LedgerSink for RecordingLedger {
    fn publish<'a>(&'a self, event: &'a UsageEvent) -> LedgerFuture<'a> {
        Box::pin(async move {
            let delay = *self.delay.lock().expect("delay");
            if !delay.is_zero() {
                tokio::time::sleep(delay).await;
            }
            {
                let mut refusals = self.refusals.lock().expect("refusals");
                if *refusals > 0 {
                    *refusals -= 1;
                    return Err(LedgerError::Publish(
                        "refused by the test ledger".to_owned(),
                    ));
                }
            }
            let envelope = event.sign(&self.signer)?;
            self.messages
                .lock()
                .expect("messages")
                .push((event.message_id(), envelope));
            Ok(())
        })
    }
}

