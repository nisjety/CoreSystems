struct Keys {
    jwt_encoding: EncodingKey,
    jwt_decoding: DecodingKey,
    event_signing_pem: Vec<u8>,
    event_verify_pem: Vec<u8>,
}

fn keys() -> &'static Keys {
    static KEYS: OnceLock<Keys> = OnceLock::new();
    KEYS.get_or_init(|| {
        let jwt = RsaPrivateKey::new(&mut rand::thread_rng(), 2048).expect("jwt key");
        let jwt_private_pem = jwt.to_pkcs8_pem(LineEnding::LF).expect("jwt pem");
        let jwt_public_pem = RsaPublicKey::from(&jwt)
            .to_public_key_pem(LineEnding::LF)
            .expect("jwt public pem");
        let event = RsaPrivateKey::new(&mut rand::thread_rng(), 2048).expect("event key");
        let event_private_pem = event.to_pkcs8_pem(LineEnding::LF).expect("event pem");
        let event_public_pem = RsaPublicKey::from(&event)
            .to_public_key_pem(LineEnding::LF)
            .expect("event public pem");
        Keys {
            jwt_encoding: EncodingKey::from_rsa_pem(jwt_private_pem.as_bytes()).expect("enc"),
            jwt_decoding: DecodingKey::from_rsa_pem(jwt_public_pem.as_bytes()).expect("dec"),
            event_signing_pem: event_private_pem.as_bytes().to_vec(),
            event_verify_pem: event_public_pem.as_bytes().to_vec(),
        }
    })
}

/// The golden token's claims, re-based onto this clock (same offsets as the golden).
fn golden_claims(name: &str) -> Map<String, Value> {
    let token = &claims_golden()["tokens"][name];
    let mut claims = token["claims"].as_object().expect("golden claims").clone();
    let (iat, nbf, exp) = (
        claims["iat"].as_i64().expect("iat"),
        claims["nbf"].as_i64().expect("nbf"),
        claims["exp"].as_i64().expect("exp"),
    );
    let now = chrono::Utc::now().timestamp();
    claims.insert("iat".into(), json!(now));
    claims.insert("nbf".into(), json!(now + (nbf - iat)));
    claims.insert("exp".into(), json!(now + (exp - iat)));
    claims
}

fn sign(claims: &Map<String, Value>) -> String {
    let mut header = Header::new(Algorithm::RS256);
    header.kid = claims_golden()["tokens"][SERVICE]["header"]["kid"]
        .as_str()
        .map(str::to_owned);
    encode(&header, claims, &keys().jwt_encoding).expect("sign")
}

/// A quarry-edge service token with exactly the scopes given.
fn service_token(scopes: &[&str]) -> String {
    let mut claims = golden_claims(SERVICE);
    claims.insert("scopes".into(), json!(scopes));
    sign(&claims)
}

fn with(mut claims: Map<String, Value>, key: &str, value: Value) -> Map<String, Value> {
    claims.insert(key.into(), value);
    claims
}

/// A token that passes the real validator and carries the signed `zdr` claim of a ZDR org.
fn zdr_service_token() -> String {
    let mut claims = golden_claims(SERVICE);
    claims.insert("scopes".into(), json!(["data:rerank"]));
    sign(&with(claims, "zdr", json!(true)))
}

fn user_token() -> String {
    sign(&golden_claims(MEMBER))
}

