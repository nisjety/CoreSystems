//! QB-T05a — `POST /v1/rerank`: the Data Plane's rerank of caller-supplied
//! candidates (Quarry option B). These contract tests apply the REAL rules, hermetically:
//!
//!   * admission is the real `authz::guard_middleware` -> `admit()`, with the real JWT
//!     validator (`strict_validation_for` + `decode_verified_claims`). Tokens are re-signed
