/// An attestation that admits the provider for ZDR content (the double of a signed attestation).
struct AttestedProvider;

impl EgressAttestation for AttestedProvider {
    fn permits_rerank(&self) -> bool {
        true
    }
}

struct Harness {
    base: String,
    provider: Provider,
    audit: Arc<RecordingAudit>,
    ledger: Arc<RecordingLedger>,
    budget: Arc<MemoryBudget>,
}

async fn spawn_app(state: RerankState) -> String {
    let app: axum::Router = rerank_api::router(state);
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind app");
    let addr = listener.local_addr().expect("addr");
    tokio::spawn(async move {
        let _ = axum::serve(listener, app).await;
    });
    format!("http://{addr}")
}

async fn harness(opts: Opts) -> Harness {
    let provider = start_provider().await;
    let availability = RouteAvailability::from_endpoint(opts.endpoint);
    let client = match availability {
        RouteAvailability::Available => Some(
            RerankClient::for_route(
                reqwest::Client::builder()
                    .danger_accept_invalid_certs(true)
                    .resolve(PROVIDER_HOST, provider.addr),
                "test-provider-key",
                MODEL,
                opts.endpoint,
                false,
            )
            .expect("provider client"),
        ),
        RouteAvailability::Misconfigured(_) => None,
    };
    let audit = Arc::new(RecordingAudit::default());
    let ledger = Arc::new(RecordingLedger::new());
    let budget = Arc::new(MemoryBudget {
        delay: opts.budget_delay,
        ..MemoryBudget::default()
    });
    let cost = opts
        .with_cost
        .then(|| Arc::new(CostLedger::new(ledger.clone())));
    let state = RerankState {
        settings: RerankSettings {
            enabled: opts.enabled,
            processor_approved: opts.processor_approved,
            allowed_services: vec!["service:quarry-edge".to_owned()],
            daily_unit_budget: opts.budget_limit,
        },
        availability,
        provider: client,
        model: MODEL.to_owned(),
        guard: AuthGuard::new(
            Arc::new(NoopPolicyClient),
            audit.clone(),
            Arc::new(PinnedKeyVerifier),
        ),
        limiter: Arc::new(FixedGate(opts.allow_rate)),
        cost,
        budget: budget.clone(),
        attestation: if opts.attested {
            Arc::new(AttestedProvider) as Arc<dyn EgressAttestation>
        } else {
            Arc::new(NoAttestation) as Arc<dyn EgressAttestation>
        },
        circuit: if opts.open_circuit {
            Arc::new(OpenCircuit) as Arc<dyn CircuitGate>
        } else {
            Arc::new(ClosedCircuit) as Arc<dyn CircuitGate>
        },
        cache: rerank_api::RerankCache::new(),
    };
    let base = spawn_app(state).await;
    Harness {
        base,
        provider,
        audit,
        ledger,
        budget,
    }
}

async fn post(
    base: &str,
    token: Option<&str>,
    body: &Value,
    org_header: Option<&str>,
) -> (StatusCode, Value) {
    let client = reqwest::Client::new();
    let mut request = client.post(format!("{base}/v1/rerank")).json(body);
    if let Some(token) = token {
        request = request.bearer_auth(token);
    }
    if let Some(org) = org_header {
        request = request.header("x-org-id", org);
    }
    let response = request.send().await.expect("request");
    let status = StatusCode::from_u16(response.status().as_u16()).expect("status");
    let text = response.text().await.expect("body");
    let value = serde_json::from_str(&text).unwrap_or(Value::String(text));
    (status, value)
}

fn documents(count: usize) -> Vec<Value> {
    (0..count)
        .map(|i| {
            json!({
                "id": format!("doc-{i}"),
                "text": format!("Public page text {i} about the cleaning schedule for solar panels."),
            })
        })
        .collect()
}

fn request(request_id: &str, docs: &[Value]) -> Value {
    json!({
        "request_id": request_id,
        "query": "how often should solar panels be cleaned",
        "profile": "web-v1",
        "zdr_mode": "disabled",
        "sovereign_required": false,
        "documents": docs,
    })
}

fn decoded_costs(ledger: &RecordingLedger) -> Vec<Value> {
    let verifier = EventVerifier::from_rsa_pem(
        &keys().event_verify_pem,
        "service:retrieval-engine-rs",
        "retrieval-events-v1",
        EVENT_AUDIENCE,
        "events:retrieval:publish",
        10_000,
    )
    .expect("verifier");
    ledger
        .messages
        .lock()
        .expect("messages")
        .iter()
        .map(|(_, envelope)| {
            let verified = verifier
                .verify("dataplane.cost.ledger", envelope)
                .expect("the real verifier accepts the signed cost envelope");
            serde_json::from_slice(&verified.payload).expect("payload json")
        })
        .collect()
}

/// The broker de-duplication id of each recorded event, in publish order.
fn cost_message_ids(ledger: &RecordingLedger) -> Vec<String> {
    ledger
        .messages
        .lock()
        .expect("messages")
        .iter()
        .map(|(id, _)| id.clone())
        .collect()
}

/// The CR-T10 golden, read through its pin (a missing or altered file FAILS, never skips).
fn usage_golden() -> &'static Value {
    static GOLDEN: OnceLock<Value> = OnceLock::new();
    GOLDEN.get_or_init(|| read_pinned(USAGE_GOLDEN))
}

/// The payload of the golden's `web-rerank-units` case. The case is read through its signed
/// envelope and verified with the producer key the golden lists, so its shape is only used once
/// it is authentic: a forged or edited golden fails here.
fn golden_web_rerank_payload() -> Value {
    let golden = usage_golden();
    let case = golden["cases"]
        .as_array()
        .expect("cases")
        .iter()
        .find(|case| case["name"] == "web-rerank-units")
        .expect("the golden has a web-rerank-units case");
    let producer = &golden["producers"][case["producer"].as_str().expect("producer")];
    let verifier = EventVerifier::from_rsa_pem(
        producer["public_key_pem"].as_str().expect("key").as_bytes(),
        producer["issuer"].as_str().expect("issuer"),
        producer["key_id"].as_str().expect("kid"),
        EVENT_AUDIENCE,
        producer["scope"].as_str().expect("scope"),
        100,
    )
    .expect("verifier");
    let envelope = case["envelope"].as_str().expect("envelope").as_bytes();
    let payload = match verifier.verify("dataplane.cost.ledger", envelope) {
        Ok(verified) => verified.payload,
        // The golden is signed with a two-minute lifetime; an expired envelope is authentic.
        Err(EnvelopeError::Expired(verified)) => verified.payload,
        Err(error) => panic!("the golden's web-rerank case is not authentic: {error}"),
    };
    serde_json::from_slice(&payload).expect("payload json")
}

fn results_ids(body: &Value) -> Vec<String> {
    body["results"]
        .as_array()
        .expect("results")
        .iter()
        .map(|r| r["id"].as_str().expect("id").to_owned())
        .collect()
}

/// The unit budget is counted in a background task, off the answer's path. Waits, at most two
/// seconds, until it holds `expected`, and returns what it holds.
async fn budget_total_within(budget: &MemoryBudget, expected: u64) -> u64 {
    for _ in 0..200 {
        if *budget.total.lock().expect("total") == expected {
            break;
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    }
    *budget.total.lock().expect("total")
}

