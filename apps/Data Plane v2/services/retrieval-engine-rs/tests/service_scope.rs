/// Control's answer for an interactive member. Membership is QB-T03's concern;
/// this file tests what confinement does after admission.
struct Member;

#[async_trait]
impl PolicyClient for Member {
    async fn resolve(&self, _user_id: &str, _org_id: &str) -> PolicyDecision {
        PolicyDecision {
            is_member: true,
            acl: EffectiveAcl::allow_all(),
            cause: "member".into(),
        }
    }
}

/// The request the HTTP boundary builds for `POST /v1/retrieve`: the real admission
/// decision, the request context overlaid the way `guard_middleware` does it, then
/// `apply_to_request`, exactly as the `retrieve` handler runs it.
async fn boundary(claims: &Claims, body: Value) -> RetrievalRequest {
    let request = AdmissionRequest {
        method: "POST",
        matched_path: Some("/v1/retrieve"),
        org_header: None,
    };
    let admitted = match admit(claims, &request, &Member).await {
        Admission::Admitted(admitted) => admitted,
        Admission::Denied(denial) => panic!("the minted token must be admitted: {denial:?}"),
    };
    let mut ctx =
        auth_context_from_verified_claims(claims, "request-1".into(), "not-a-token".into());
    ctx.principal = admitted.principal;
    ctx.acl = admitted.acl;
    ctx.scopes = admitted.scopes;
    let mut req: RetrievalRequest = serde_json::from_value(body).expect("the body parses");
    ctx.apply_to_request(&mut req);
    req
}

/// What a client can send. Whatever it names, a confined request names the quarry
/// corpus and the dense-only blend.
fn client_bodies(org: &str) -> Vec<Value> {
    vec![
        json!({"org_id": org, "query": "pump seal replacement"}),
        json!({"org_id": org, "query": "pump seal replacement", "filters": {"sources": []}}),
        json!({"org_id": org, "query": "pump seal replacement",
               "filters": {"sources": ["sharepoint"]}}),
        json!({"org_id": org, "query": "pump seal replacement",
               "filters": {"sources": ["quarry", "chat-upload"]}}),
        json!({"org_id": org, "query": "pump seal replacement",
               "filters": {"sources": ["sharepoint"], "document_ids": ["sp-1"]}}),
        json!({"org_id": org, "query": "pump seal replacement",
               "mode_mix": {"w_dense": 0.0, "w_bm25": 1.0, "w_graph": 0.5, "w_wiki": 0.5,
                            "w_visual": 0.5, "w_keyword": 0.5, "rerank": true}}),
    ]
}

