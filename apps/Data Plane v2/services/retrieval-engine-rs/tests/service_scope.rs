#[tokio::test]
async fn the_pipeline_routes_a_confined_service_request_dense_only() {
    let claims = quarry_claims();
    let org = org_of(&claims);
    // The client asks for a sparse-and-graph blend over SharePoint, with rerank on.
    let req = boundary(
        &claims,
        json!({"org_id": org, "query": "pump seal replacement",
               "filters": {"sources": ["sharepoint"]},
               "mode_mix": {"w_dense": 0.0, "w_bm25": 1.0, "w_graph": 1.0, "rerank": true}}),
    )
    .await;
    let pipeline = pipeline_with_closed_backends().await;
    let buffer = LogBuffer::default();
    let subscriber = tracing_subscriber::fmt()
        .with_writer(buffer.clone())
        .with_ansi(false)
        .with_max_level(tracing::Level::INFO)
        .finish();
    // The dense arm needs a query embedding, which the closed model plane refuses,
    // so the request stops there. The route was decided before that, and it is logged.
    let _ = pipeline.retrieve(req).with_subscriber(subscriber).await;
    let logs = buffer.text();
    let start = logs
        .lines()
        .find(|line| line.contains("retrieval.start"))
        .unwrap_or_else(|| panic!("the pipeline logs retrieval.start: {logs}"));
    assert!(start.contains("route_dense=true"), "{start}");
    assert!(start.contains("route_sparse=false"), "{start}");
}

