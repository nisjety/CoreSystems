#[test]
fn the_confined_blend_is_dense_only_and_never_reranks() {
    let resolved = confined_mode_mix().resolve(0.45, 0.2, 0.2, 0.1, 0.05, 0.05, 60.0);
    assert_eq!(
        EngineRoute::from_weights(&resolved, true),
        EngineRoute {
            dense: true,
            sparse: false
        }
    );
    for (arm, weight) in [
        ("bm25", resolved.w_bm25),
        ("graph", resolved.w_graph),
        ("wiki", resolved.w_wiki),
        ("visual", resolved.w_visual),
        ("keyword", resolved.w_keyword),
    ] {
        assert_eq!(weight, 0.0, "the {arm} arm stays off for a service");
    }
    assert!(
        (resolved.w_dense - 1.0).abs() < 1e-6,
        "dense carries the blend"
    );
    assert!(
        !resolved.rerank,
        "Quarry reranks through /v1/rerank, not here"
    );
}

