/// The schema slice the gate reads. Other suites create `documents` with other
/// shapes, so every column this test needs is added if it is missing.
async fn seed_schema(pool: &PgPool) {
    sqlx::raw_sql(
        r#"
        CREATE TABLE IF NOT EXISTS documents (
            document_id TEXT PRIMARY KEY,
            org_id      TEXT NOT NULL
        );
        ALTER TABLE documents ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT '';
        ALTER TABLE documents ADD COLUMN IF NOT EXISTS owner_id TEXT NOT NULL DEFAULT 'org-system-account';
        ALTER TABLE documents ADD COLUMN IF NOT EXISTS visibility TEXT NOT NULL DEFAULT 'org';
        ALTER TABLE documents ADD COLUMN IF NOT EXISTS zdr_classification TEXT NOT NULL DEFAULT 'internal';
        ALTER TABLE documents ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;
        CREATE TABLE IF NOT EXISTS wiki_pages (
            page_id     TEXT PRIMARY KEY,
            org_id      TEXT NOT NULL,
            page_status TEXT NOT NULL DEFAULT 'draft'
        );
        "#,
    )
    .execute(pool)
    .await
    .expect("create the gate's schema");
    common::grant_rls_runtime_role(pool).await;
}

/// One org's mixed corpus: Quarry crawl documents (one org-visible, one private to
/// another user), a SharePoint document and a chat upload, and a published wiki page.
async fn seed_mixed_corpus(pool: &PgPool, org: &str) {
    seed_schema(pool).await;
    let documents = [
        ("q-org", "quarry", "org-system-account", "org"),
        ("q-org-2", "quarry", "org-system-account", "org"),
        ("q-private", "quarry", "user-a", "private"),
        ("sp-org", "sharepoint", "org-system-account", "org"),
        ("ch-org", "chat-upload", "org-system-account", "org"),
    ];
    for (name, source, owner, visibility) in documents {
        sqlx::query(
            "INSERT INTO documents (document_id, org_id, source, owner_id, visibility) \
             VALUES ($1, $2, $3, $4, $5)",
        )
        .bind(format!("{org}-{name}"))
        .bind(org)
        .bind(source)
        .bind(owner)
        .bind(visibility)
        .execute(pool)
        .await
        .expect("seed a document");
    }
    sqlx::query(
        "INSERT INTO wiki_pages (page_id, org_id, page_status) VALUES ($1, $2, 'published')",
    )
    .bind(format!("{org}-wiki-1"))
    .bind(org)
    .execute(pool)
    .await
    .expect("seed a published wiki page");
}

async fn gate_keeps(gate: &VisibilityGate<'_>, candidates: Vec<ScoredCandidate>) -> Vec<String> {
    let mut ctx = PostprocessCtx::new("pump seal replacement", ZdrMode::Disabled, false);
    let mut kept: Vec<String> = gate
        .postprocess(candidates, &mut ctx)
        .await
        .expect("the visibility gate query")
        .into_iter()
        .map(|candidate| candidate.document_id)
        .collect();
    kept.sort();
    kept
}

