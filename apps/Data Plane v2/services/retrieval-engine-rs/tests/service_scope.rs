//! QB-M1a: the engine confines a service principal's retrieval to the corpus it
//! is granted, on the real request path.
//!
//! Quarry's vector leg asks `POST /v1/retrieve` for its own crawl corpus. Before
//! this change the engine honoured whatever `filters.sources` and `mode_mix` the
//! request carried, so a service could name any corpus, and the dense arm's
//! `source` condition matched nothing at all (stored points carry no such key
//! until the embedding engine stamps it). The enforcement is server-side and has
//! three layers:
//!
//!   1. `service_routes::confine_request` REPLACES a service's `filters.sources`
//!      with its corpus and its blend with the dense-only, no-rerank blend. It runs
//!      before the cache key, the arms, the overfetch trim and the trace see the
//!      request, so a client value can narrow the result and never widen it.
//!   2. The dense arm filters on the stamped Qdrant payload key `source`.
//!   3. The post-fusion visibility gate repeats the corpus test on
//!      `documents.source`. It is defence in depth behind the dense filter.
//!
//! The hermetic tests drive the REAL admission decision and the REAL request
//! boundary (`admit`, `auth_context_from_verified_claims`, `apply_to_request`)
//! over claims that Auth Core's mint wrote: the sha256-pinned goldens in
//! `tests/fixtures/auth-core`. Nothing in them skips. The database and Qdrant
//! tests at the end are `#[ignore]`d and need `TEST_DATABASE_URL` and
//! `TEST_QDRANT_URL`. Under CI or REQUIRE_CONTRACT a missing variable fails them
//! instead of letting them skip.

