/// The value of an environment variable a gated test needs, or `None` when the
/// test skips. Under CI or REQUIRE_CONTRACT a missing value fails the test.
fn env_or_skip(name: &str) -> Option<String> {
    let value = std::env::var(name)
        .ok()
        .filter(|value| !value.trim().is_empty());
    if value.is_none() {
        if std::env::var_os("CI").is_some() || std::env::var_os("REQUIRE_CONTRACT").is_some() {
            panic!("{name} is not set but CI or REQUIRE_CONTRACT is: a gated test that skips proves nothing");
        }
        eprintln!("skipped: {name} is not set");
    }
    value
}

