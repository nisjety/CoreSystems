/// Reads one Auth Core golden and checks it against its sha256 pin. A missing or
/// altered golden fails the test; it is regenerated by Auth Core, never by hand.
fn read_pinned(name: &str) -> Value {
    let path = format!("{FIXTURES}/{name}");
    let bytes = std::fs::read(&path).unwrap_or_else(|error| {
        panic!("contract golden {path} is missing ({error}); Auth Core regenerates it")
    });
    let pin = std::fs::read_to_string(format!("{path}.sha256"))
        .unwrap_or_else(|error| panic!("pin {path}.sha256 is missing ({error})"));
    let expected = pin
        .split_whitespace()
        .next()
        .expect("the pin file holds a sha256");
    // Pinned over the LF-normalised bytes: a Windows checkout may rewrite line endings.
    let normalised: Vec<u8> = bytes.iter().copied().filter(|b| *b != b'\r').collect();
    let actual = format!("{:x}", Sha256::digest(&normalised));
    assert_eq!(
        actual, expected,
        "{name} no longer matches its sha256 pin; Auth Core must regenerate it"
    );
    serde_json::from_slice(&bytes).expect("the golden is JSON")
}

/// The verified claims one token Auth Core minted, as the engine deserializes them.
fn minted_claims(token: &str) -> Claims {
    let golden = read_pinned(CLAIMS_GOLDEN);
    let claims = golden["tokens"][token]["claims"].clone();
    serde_json::from_value(claims)
        .unwrap_or_else(|error| panic!("{token} claims do not deserialize: {error}"))
}

fn quarry_claims() -> Claims {
    minted_claims("serviceQuarryEdgeDataRead")
}

fn member_claims() -> Claims {
    minted_claims("interactiveMember")
}

fn org_of(claims: &Claims) -> String {
    claims
        .org_id
        .clone()
        .expect("the minted token carries its organization")
}

