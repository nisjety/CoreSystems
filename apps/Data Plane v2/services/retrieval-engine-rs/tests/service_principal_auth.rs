/// The claims of one golden token, with iat/nbf/exp re-based on this clock and
/// the golden's own offsets (nbf = iat - 5, exp = iat + the audience TTL).
fn claims_of(name: &str) -> Map<String, Value> {
    let token = &claims_golden()["tokens"][name];
    let mut claims = token["claims"]
        .as_object()
        .unwrap_or_else(|| panic!("golden token {name} has no claims"))
        .clone();
    let (iat, nbf, exp) = (
        claims["iat"].as_i64().expect("iat"),
        claims["nbf"].as_i64().expect("nbf"),
        claims["exp"].as_i64().expect("exp"),
    );
    let now = chrono::Utc::now().timestamp();
    claims.insert("iat".into(), json!(now));
    claims.insert("nbf".into(), json!(now + (nbf - iat)));
    claims.insert("exp".into(), json!(now + (exp - iat)));
    claims
}

fn sign_with(claims: &Map<String, Value>, key: &EncodingKey) -> String {
    let mut header = Header::new(Algorithm::RS256);
    header.kid = claims_golden()["tokens"][SERVICE]["header"]["kid"]
        .as_str()
        .map(str::to_owned);
    encode(&header, claims, key).expect("sign token")
}

fn sign(claims: &Map<String, Value>) -> String {
    sign_with(claims, &keys().encoding)
}

fn token_of(name: &str) -> String {
    sign(&claims_of(name))
}

fn service_claims() -> Map<String, Value> {
    claims_of(SERVICE)
}

/// The service token a caller holding `scopes` would have been issued. The
/// shape is the real mint's; only the scope list differs, and the registry (not
/// the engine) decides which scopes a principal may hold.
fn service_claims_with_scopes(scopes: &[&str]) -> Map<String, Value> {
    let mut claims = service_claims();
    claims.insert("scopes".into(), json!(scopes));
    claims
}

fn with(mut claims: Map<String, Value>, key: &str, value: Value) -> Map<String, Value> {
    claims.insert(key.into(), value);
    claims
}

fn without(mut claims: Map<String, Value>, key: &str) -> Map<String, Value> {
    claims.remove(key);
    claims
}

