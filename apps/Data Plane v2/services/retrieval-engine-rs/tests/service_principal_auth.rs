#[derive(Debug, Clone)]
struct AuditRow {
    user_id: Option<String>,
    org_id: String,
    endpoint: String,
    http_status: u16,
    cause: String,
}

#[derive(Default)]
struct RecordingAudit(Mutex<Vec<AuditRow>>);

#[async_trait::async_trait]
impl AuditSink for RecordingAudit {
    async fn record(&self, event: AccessEvent<'_>) {
        self.0.lock().expect("audit lock").push(AuditRow {
            user_id: event.ctx.user_id.clone(),
            org_id: event.ctx.org_id.clone(),
            endpoint: event.endpoint.to_owned(),
            http_status: event.http_status,
            cause: event.cause.to_owned(),
        });
    }
}

