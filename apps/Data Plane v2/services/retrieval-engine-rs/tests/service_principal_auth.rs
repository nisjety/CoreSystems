fn read_pinned(name: &str) -> Value {
    let path = format!("{FIXTURES}/{name}");
    let bytes = std::fs::read(&path).unwrap_or_else(|error| {
        panic!("contract golden {path} is missing ({error}); regenerate it with UPDATE_CONTRACT_GOLDEN=1 from Auth Core")
    });
    let pin = std::fs::read_to_string(format!("{path}.sha256"))
        .unwrap_or_else(|error| panic!("pin {path}.sha256 is missing ({error})"));
    let expected = pin
        .split_whitespace()
        .next()
        .expect("pin file holds a sha256");
    // Pinned over the LF-normalised bytes: a Windows checkout may rewrite line endings.
    let normalised: Vec<u8> = bytes.iter().copied().filter(|b| *b != b'\r').collect();
    let actual = format!("{:x}", Sha256::digest(&normalised));
    assert_eq!(
        actual, expected,
        "{name} no longer matches its sha256 pin; it must be regenerated by Auth Core, never edited"
    );
    serde_json::from_slice(&bytes).expect("golden is JSON")
}

