#[test]
fn goldens_are_pinned_and_carry_the_claim_keys_auth_core_really_emits() {
    let tokens = claims_golden()["tokens"].as_object().expect("tokens");
    assert!(
        tokens.contains_key(SERVICE) && tokens.contains_key(MEMBER) && tokens.contains_key(ADMIN)
    );
    for (name, token) in tokens {
        let mut keys: Vec<String> = token["claims"]
            .as_object()
            .expect("claims")
            .keys()
            .cloned()
            .collect();
        keys.sort();
        let recorded: Vec<String> = token["claimKeys"]
            .as_array()
            .expect("claimKeys")
            .iter()
            .map(|key| key.as_str().expect("key").to_owned())
            .collect();
        assert_eq!(keys, recorded, "{name}");
    }
    // The shape the engine's service branch depends on.
    let service = &tokens[SERVICE]["claims"];
    assert_eq!(service["principal_type"], "service");
    assert_eq!(service["sub"], service["service_id"]);
    assert!(service.get("user_id").is_none());
    assert!(service.get("acting_user_id").is_none());
    assert!(service["zdr"].is_boolean());
    decision_golden();
}
