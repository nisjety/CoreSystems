// ───────────────────────── loopback Control (golden decision bodies) ─────────────────────────

#[derive(Default)]
struct ControlState {
    token_requests: AtomicUsize,
    decision_requests: AtomicUsize,
    decision_bodies: Mutex<Vec<Value>>,
}

async fn control_token(
    State(state): State<Arc<ControlState>>,
    Json(body): Json<Value>,
) -> Json<Value> {
    state.token_requests.fetch_add(1, Ordering::SeqCst);
    let now = chrono::Utc::now().timestamp();
    let org = body["orgId"].as_str().unwrap_or_default();
    let claims = json!({
        "iss": issuer(),
        "aud": "control-policy",
        "sub": "service:retrieval-engine",
        "iat": now,
        "nbf": now - 5,
        "exp": now + 60,
        "org_id": org,
        "principal_type": "service",
        "service_id": "service:retrieval-engine",
        "scopes": ["data:authorization:decide"],
        "reason": "authorize retrieval request",
    });
    let mut header = Header::new(Algorithm::RS256);
    header.typ = Some("JWT".into());
    let jwt = encode(&header, &claims, &keys().encoding).expect("policy token");
    Json(json!({
        "token": jwt,
        "expiresAt": chrono::DateTime::from_timestamp(now + 60, 0).unwrap().to_rfc3339(),
        "expiresInSeconds": 60,
        "issuer": issuer(),
        "audience": "control-policy",
    }))
}

/// Answers with the body Auth Core's real decision controller produced for the
/// matching golden subject, and the golden `not_member` for every other subject
/// (no `member` row exists for them either).
async fn control_decision(
    State(state): State<Arc<ControlState>>,
    headers: axum::http::HeaderMap,
    Json(body): Json<Value>,
) -> (StatusCode, Json<Value>) {
    state.decision_requests.fetch_add(1, Ordering::SeqCst);
    state
        .decision_bodies
        .lock()
        .expect("decision lock")
        .push(body.clone());
    if headers.get("authorization").is_none() {
        return (
            StatusCode::UNAUTHORIZED,
            Json(json!({"error": "no bearer"})),
        );
    }
    let decisions = &decision_golden()["decisions"];
    let user = body["userId"].as_str().unwrap_or_default();
    let key = ["memberRead", "adminRead"]
        .into_iter()
        .find(|key| decisions[*key]["request"]["userId"] == user)
        .unwrap_or("serviceSubjectNotMember");
    (StatusCode::OK, Json(decisions[key]["response"].clone()))
}

struct Control {
    token_url: String,
    decision_url: String,
    state: Arc<ControlState>,
}

async fn start_control() -> Control {
    // Generate the (slow, debug-build) RSA key BEFORE any request is in flight.
    // `control_token` signs with it inside an async handler on this test's
    // single-threaded runtime; a lazy first use there would block the runtime
    // for the whole key generation and make the real `HttpPolicyClient`'s 3 to
    // 7 second request timeouts expire (`denied:control_plane_unavailable`).
    let _ = keys();
    let state = Arc::new(ControlState::default());
    let app = Router::new()
        .route(
            "/api/control-policy/internal-token",
            axum::routing::post(control_token),
        )
        .route(
            "/api/v1/internal/authorization/data-plane/decision",
            axum::routing::post(control_decision),
        )
        .with_state(state.clone());
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind control");
    let addr = listener.local_addr().expect("control addr");
    tokio::spawn(async move {
        axum::serve(listener, app).await.expect("serve control");
    });
    Control {
        token_url: format!("http://{addr}/api/control-policy/internal-token"),
        decision_url: format!("http://{addr}/api/v1/internal/authorization/data-plane/decision"),
        state,
    }
}

fn real_policy(control: &Control) -> HttpPolicyClient {
    HttpPolicyClient::new(
        control.token_url.clone(),
        control.decision_url.clone(),
        "retrieval-engine",
        "contract-test-credential",
    )
}

