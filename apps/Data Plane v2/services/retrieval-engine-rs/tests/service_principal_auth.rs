//! QB-T03 — principal-aware admission for the retrieval engine's HTTP surface.
//!
//! Live defect (2026-10-01): quarry-edge's `POST /v1/retrieve` answered 403 on
//! every call. Auth Core signs a valid service token (`sub=service:quarry-edge`,
//! `principal_type=service`, no `user_id`), and the engine pushed that subject
//! through the USER membership lookup. Auth Core's real decision for a service
//! subject is `not_member` (no `member` row exists for `service:*`), so every
//! service call was denied. The engine's own tests used a permissive membership
//! double and could not see it.
//!
//! This file applies the REAL rules, hermetically (no Postgres, no network
//! beyond loopback):
//!
//!   * tokens are re-signed from goldens that Auth Core's real mint wrote
//!     (`tests/fixtures/auth-core/*.golden.json`, sha256-pinned; the Auth Core
//!     jest spec `data-plane-service-principal.contract.spec.ts` regenerates
//!     them and fails when they drift). A missing or altered golden FAILS here;
//!     nothing in this file skips.
//!   * the JWT is validated by the real `strict_validation_for` +
//!     `decode_verified_claims` (required `zdr`, issuer, audience, RS256 only).
//!   * the policy client is the real `HttpPolicyClient`, talking to a loopback
//!     Control that answers with the golden decision bodies Auth Core's real
//!     `DataPlaneAuthorizationController.decide` produced.
//!   * the middleware is the real `authz::guard_middleware`, mounted with
//!     `route_layer` on routes whose paths are SCANNED from the real router
//!     (`src/api/mod.rs`), so a route added later is automatically swept.
//!
//! The only doubles are the audit sink (no database) and the visibility facade
//! (a counter, to prove it is never called for a service principal).

