#[test]
fn only_the_health_probes_and_metrics_sit_outside_the_guard() {
    assert_eq!(
        unguarded_routes(),
        ["/health", "/metrics", "/readyz"]
            .into_iter()
            .map(str::to_owned)
            .collect::<BTreeSet<_>>(),
        "a route registered outside the auth guard bypasses admission entirely"
    );
    let router = slice_between(
        API_SOURCE,
        "fn router_inner(",
        "let mut app = Router::new()",
    );
    assert!(
        router.contains("guard_middleware"),
        "router_inner must mount authz::guard_middleware on the authed routes"
    );
    // This file mounts its own copy of the guard, so the production wiring is
    // pinned here: it must be `route_layer` (never `layer`). Only a route layer
    // sees the matched route PATTERN the service allowlist is keyed on; mounted
    // as a plain layer every service call would resolve to no pattern and be
    // refused, which is the 403 defect again.
    let wiring = regex::Regex::new(
        r"\.route_layer\(\s*middleware::from_fn_with_state\(\s*auth_guard\(&state\),\s*crate::authz::guard_middleware,?\s*\)\s*\)",
    )
    .expect("wiring regex");
    assert!(
        wiring.is_match(router),
        "the admission guard must be mounted with route_layer(from_fn_with_state(auth_guard(&state), guard_middleware))"
    );
}

