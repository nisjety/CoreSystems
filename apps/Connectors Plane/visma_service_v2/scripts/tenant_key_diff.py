#!/usr/bin/env python3
"""Per tenant and endpoint: which rows does v1 hold that v2 did not fetch?

`v1_v2_key_diff.py` does this for the pilot tenant alone. After `tenant_sweep.py` has run every
endpoint for the other tenants into one scratch database, this repeats it for each of them:
DISTINCT keys under v1's primary key, v1's not-deleted rows (read-only `bq`) against the v2 rows of
that tenant. Endpoints whose v1 table does not exist, whose key is not a plain column of the v1
table, or that have no v2 counterpart are left out, with the reason.

It does not say why a v1-only key is missing (deleted in Visma and never removed by v1, or a v2
miss); `v1_v2_key_diff.py` and `docs/v1_vs_v2_gaps.md` show how to tell those apart.

Usage: scripts/tenant_key_diff.py --db vsv2_alltenants_20260930 [--tenants id,id] [--only a,b]
Writes docs/tenant_v1_key_diff.md (only for a run without --tenants and --only).
"""

from __future__ import annotations

import argparse
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import reconcile_sources as rs  # noqa: E402
import tenant_scan_compare as tenants  # noqa: E402
import v1_v2_key_diff as kd  # noqa: E402
import v1_v2_row_counts as counts  # noqa: E402

OUT = ROOT / "docs/tenant_v1_key_diff.md"
PROJECT = "prj-dw-dev"


def v2_keys(db: str, tenant: str, endpoint: str, fields: list[str]) -> set[str] | str:
    columns = ", ".join(rs.json_path(f) for f in fields)
    sql = (
        f"select {columns} from vsv2.local_bronze_record "
        f"where endpoint = '{endpoint}' and tenant_id = '{tenant}'"
    )
    keys, blank = set(), 0
    for line in rs.psql(db, sql):
        parts = [p.strip() for p in line.split(rs.SEP)]
        if not any(parts):
            blank += 1
            continue
        keys.add("|".join(parts))
    return keys if keys or not blank else f"v2 rows lack {', '.join(fields)}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True)
    ap.add_argument("--tenants", default="")
    ap.add_argument("--only", default="")
    args = ap.parse_args()
    chosen = {t for t in args.tenants.split(",") if t}
    only = {n for n in args.only.split(",") if n}

    v1 = counts.load_v1()
    v2_configs = rs.load_configs()
    names = [
        n
        for n in sorted(v1)
        if n not in counts.DERIVED
        and counts.V1_TO_V2.get(n, n) in v2_configs
        and (not only or n in only)
    ]
    todo = [
        (t, n) for t, n, _ in tenants.TENANTS if t != tenants.PILOT and (not chosen or t in chosen)
    ]

    def job(item: tuple[tuple[str, str], str]):
        (tenant, tenant_name), name = item
        fields = counts.as_list(v1[name]["primary_key"])
        table = v1[name].get("bigquery_table", f"visma_{name}")
        keys1 = kd.v1_keys(PROJECT, table, tenant, fields)
        target = counts.V1_TO_V2.get(name, name)
        keys2 = v2_keys(args.db, tenant, target, fields) if isinstance(keys1, set) else keys1
        return tenant_name, name, target, keys1, keys2

    items = [(pair, name) for pair in todo for name in names]
    with ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(job, items))

    compared, skipped = [], {}
    for tenant_name, name, target, k1, k2 in results:
        if isinstance(k1, str) or isinstance(k2, str):
            skipped.setdefault(name, set()).add(k1 if isinstance(k1, str) else k2)
        else:
            compared.append((tenant_name, name, target, k1, k2))

    lines = [
        "# v1 vs v2 per tenant: rows v1 holds that v2 did not fetch",
        "",
        "> Generated by `scripts/tenant_key_diff.py` from a `tenant_sweep.py` run. Distinct keys",
        "> under v1's primary key; v1 = not-deleted rows of `dw_1_bronze_visma`, v2 = one full",
        "> fetch per endpoint and tenant. The two were fetched at different times, so rows",
        "> created in between show up on the side that was fetched later.",
        "",
        f"{len(compared)} tenant/endpoint pairs compared across {len(todo)} tenants; "
        f"{sum(1 for c in compared if c[3] - c[4])} have rows only v1 holds.",
        "",
        "## Rows only v1 holds",
        "",
        "| Tenant | Endpoint | v1 keys | v2 keys | v1 only | v2 only | sample |",
        "|---|---|---|---|---|---|---|",
    ]
    gaps = sorted(
        (c for c in compared if c[3] - c[4]),
        key=lambda c: (-len(c[3] - c[4]), c[0], c[1]),
    )
    for tenant_name, name, _target, k1, k2 in gaps:
        sample = ", ".join(sorted(k1 - k2)[:4])
        lines.append(
            f"| {tenant_name} | `{name}` | {len(k1):,} | {len(k2):,} | {len(k1 - k2):,} "
            f"| {len(k2 - k1):,} | {sample} |"
        )
    if not gaps:
        lines.append("| none | | | | | | |")
    lines += ["", "## Not compared", ""]
    lines += [f"- `{n}`: {sorted(why)[0][:140]}" for n, why in sorted(skipped.items())] or [
        "- none"
    ]
    text = "\n".join(lines) + "\n"
    if chosen or only:
        print(text)
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}: {len(compared)} compared, {len(gaps)} with gaps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
