#!/usr/bin/env python3
"""Generate docs/endpoint_matrix.md from config/endpoints/*.json and the ingest evidence.

One row per endpoint: source, upstream path or DataMart root, key, incremental field,
pagination, DataMart state, and the outcome of the last live run recorded under
docs/evidence/ingest_probe_*/summary.csv. Numbers are derived, never typed by hand, so the
document cannot drift from the configs the way "73 endpoints" did.

Live status per endpoint (from the evidence, oldest to newest):
  proven   the last failure, if any, was followed by a successful run that fetched rows
  empty    successful runs only, but none fetched a row (proves nothing about ingestion)
  failing  the newest run failed
  untested no evidence at all

Usage: scripts/endpoint_matrix.py            (writes docs/endpoint_matrix.md)
       scripts/endpoint_matrix.py --check    (exit 1 if the committed file is out of date)
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/endpoint_matrix.md"
sys.path.insert(0, str(ROOT / "tooling/src"))


def load_configs() -> dict[str, dict]:
    configs = {}
    for path in sorted((ROOT / "config/endpoints").glob("*.json")):
        if not path.name.startswith("_"):
            cfg = json.loads(path.read_text())
            configs[cfg["endpoint_name"]] = cfg
    return configs


def live_status() -> dict[str, tuple[str, int]]:
    """endpoint -> (status, max rows fetched by a successful run after the last failure)."""
    timeline: dict[str, list[tuple[bool, int]]] = {}
    for directory in sorted((ROOT / "docs/evidence").glob("ingest_probe_*")):
        summary = directory / "summary.csv"
        if not summary.exists():
            continue
        for row in csv.DictReader(summary.open()):
            name = row["endpoint"].split(":")[0].split(" ")[0]
            timeline.setdefault(name, []).append(
                (row["status"] == "succeeded", int(row["records_in"] or 0))
            )
    result = {}
    for name, runs in timeline.items():
        last_failure = max((i for i, (ok, _) in enumerate(runs) if not ok), default=-1)
        after = runs[last_failure + 1 :]
        if last_failure >= 0 and not after:
            result[name] = ("failing", 0)
        elif any(rows > 0 for _, rows in after):
            result[name] = ("proven", max(rows for _, rows in after))
        else:
            result[name] = ("empty", 0)
    return result


def datamart_state(cfg: dict, registry: set[str]) -> str:
    if cfg["source"] == "datamart_graphql":
        return "native (ready)" if (cfg.get("datamart") or {}).get("ready") else "native (off)"
    dm = cfg.get("datamart")
    if not dm:
        return "-"
    if not dm.get("root_field"):
        return "placeholder"
    normalizer = dm.get("join_normalizer")
    if dm.get("ready"):
        return "ready"
    if normalizer in registry:
        return f"shadow ({normalizer.removeprefix('normalize_')})"
    return "mapped, no normalizer" if not normalizer else f"mapped, {normalizer} missing"


def upstream(cfg: dict) -> str:
    if cfg["source"] == "datamart_graphql":
        return f"DM `{cfg['datamart']['root_field']}`"
    return f"`{cfg.get('api_endpoint') or cfg.get('api_method')}`"


def key_of(cfg: dict) -> str:
    pk = cfg["primary_key"]
    return ", ".join(pk) if isinstance(pk, list) else pk


def render() -> str:
    from vsv2_tooling.normalizers import REGISTRY

    configs = load_configs()
    status = live_status()
    rows = []
    for name, cfg in configs.items():
        state, fetched = status.get(name, ("untested", 0))
        rows.append(
            (
                name,
                cfg["source"],
                upstream(cfg),
                key_of(cfg),
                cfg.get("modified_field") or "full refresh",
                "partitioned" if cfg.get("partitioning") else cfg.get("pagination_profile", "-"),
                datamart_state(cfg, set(REGISTRY)),
                f"{state} ({fetched:,})" if state == "proven" else state,
            )
        )
    by_source = Counter(c["source"] for c in configs.values())
    by_status = Counter(status.get(n, ("untested", 0))[0] for n in configs)
    lines = [
        "# Endpoint matrix",
        "",
        "> Generated by `scripts/endpoint_matrix.py` from `config/endpoints/*.json` and the live",
        "> runs under `docs/evidence/ingest_probe_*`. Do not edit by hand; re-run the script.",
        "",
        f"**{len(configs)} endpoint configs** - "
        + ", ".join(f"{n} `{s}`" for s, n in sorted(by_source.items())),
        "",
        "Live status: "
        + ", ".join(f"{by_status[s]} {s}" for s in ("proven", "empty", "failing", "untested")),
        "",
        "- **proven**: a successful run fetched rows after the last failure (max rows in brackets)",
        "- **empty**: runs succeeded but fetched nothing, so ingestion is not proven",
        "- **failing**: the newest recorded run failed",
        "",
        "| Endpoint | Source | Upstream | Key | Incremental | Pagination | DataMart | Live |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines += [f"| `{r[0]}` | {' | '.join(r[1:])} |" for r in rows]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/endpoint_matrix.md is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/endpoint_matrix.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
