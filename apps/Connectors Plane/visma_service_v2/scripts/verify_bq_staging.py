#!/usr/bin/env python3
"""Does BigQuery staging hold what the local copies of the same fetches hold?

For every tenant and endpoint it counts the distinct keys in `dw_staging_visma.<endpoint>`
(read-only queries) and sets them next to the distinct keys of the local Postgres copies written by
earlier syncs of the same data: the multi-tenant scratch database for the 11 other tenants and the
pilot's `vsv2_ingest_*` databases. The two sides were fetched at different times, so BigQuery
can hold a few rows more (new since) but should never hold fewer.

  equal       same number of keys
  bq_more     BigQuery has more: rows created since the local fetch
  bq_less     BigQuery has fewer: rows that did not arrive, to be looked at
  bq_only     BigQuery has a table the local copies do not (or the other way round)

Usage: scripts/verify_bq_staging.py --db vsv2_alltenants_20260930 [--project P]
Writes docs/bq_staging_verification.md for a complete run.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from _bq_target import DATASET, PROJECT
from google.cloud import bigquery

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import reconcile_sources as rs  # noqa: E402
import tenant_scan_compare as tenants  # noqa: E402

OUT = ROOT / "docs/bq_staging_verification.md"


def bigquery_counts(project: str, dataset: str) -> dict[tuple[str, str], tuple[int, int]]:
    """(tenant, endpoint) -> (live keys, soft-deleted keys) over every table of the dataset."""
    client = bigquery.Client(project=project)
    names = [
        t.table_id
        for t in client.list_tables(f"{project}.{dataset}")
        if not t.table_id.startswith("__")
    ]
    parts = [
        f"SELECT '{n}' AS endpoint, tenant_id, COUNTIF(deleted_at IS NULL) AS live, "
        f"COUNTIF(deleted_at IS NOT NULL) AS gone FROM `{project}.{dataset}.{n}` GROUP BY tenant_id"
        for n in names
    ]
    found: dict[tuple[str, str], tuple[int, int]] = {}
    for start in range(0, len(parts), 40):  # keep each statement a sensible size
        sql = "\nUNION ALL\n".join(parts[start : start + 40])
        for row in client.query(sql).result():
            found[(row.tenant_id, row.endpoint)] = (row.live, row.gone)
    return found


def local_counts(db: str, only_tenants: set[str] | None = None) -> dict[tuple[str, str], int]:
    sql = (
        "select tenant_id, endpoint, count(distinct record_key) "
        "from vsv2.local_bronze_record group by 1, 2"
    )
    found: dict[tuple[str, str], int] = {}
    for line in rs.psql(db, sql):
        tenant, endpoint, count = line.split(rs.SEP)
        if only_tenants is None or tenant in only_tenants:
            found[(tenant, endpoint)] = int(count)
    return found


def pilot_counts() -> dict[tuple[str, str], int]:
    """The pilot's best local copy of each endpoint (the fullest scratch database)."""
    found: dict[tuple[str, str], int] = {}
    for endpoint, (db, _rows) in rs.locate(rs.scratch_databases()).items():
        counts = local_counts(db, {tenants.PILOT})
        if (tenants.PILOT, endpoint) in counts:
            found[(tenants.PILOT, endpoint)] = counts[(tenants.PILOT, endpoint)]
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True, help="multi-tenant scratch database of the 11 tenants")
    ap.add_argument("--project", default=PROJECT)
    ap.add_argument("--dataset", default=DATASET)
    args = ap.parse_args()

    in_bq = bigquery_counts(args.project, args.dataset)
    current = set(rs.load_configs())  # a local copy of an endpoint whose config is gone is history
    local = {
        key: count
        for key, count in {**local_counts(args.db), **pilot_counts()}.items()
        if key[1] in current
    }
    names = {t: n for t, n, _ in tenants.TENANTS}

    verdicts: dict[str, list[tuple[str, str, int, int, int]]] = defaultdict(list)
    for key in sorted(set(in_bq) | set(local)):
        tenant, endpoint = key
        live, gone = in_bq.get(key, (0, 0))
        have = local.get(key, 0)
        if key not in local:
            verdict = "bq_only"
        elif key not in in_bq:
            verdict = "bq_less" if have else "equal"
        elif live == have:
            verdict = "equal"
        else:
            verdict = "bq_more" if live > have else "bq_less"
        verdicts[verdict].append((names.get(tenant, tenant), endpoint, live, have, gone))

    total_bq = sum(live for live, _ in in_bq.values())
    lines = [
        "# BigQuery staging vs the local copies",
        "",
        "> Generated by `scripts/verify_bq_staging.py`. Distinct keys per tenant and endpoint in",
        f"> `{args.project}.{args.dataset}` against the local Postgres copies of the same fetches.",
        "> They were fetched at different times, so BigQuery may hold a few more rows (new since).",
        "",
        f"{len(in_bq)} tenant/endpoint tables with rows; {total_bq:,} live rows in BigQuery.",
        "",
        "| Verdict | Pairs |",
        "|---|---|",
    ]
    for verdict in ("equal", "bq_more", "bq_less", "bq_only"):
        lines.append(f"| {verdict} | {len(verdicts[verdict]):,} |")
    for verdict in ("bq_less", "bq_more", "bq_only"):
        if not verdicts[verdict]:
            continue
        lines += [
            "",
            f"## {verdict}",
            "",
            "| Tenant | Endpoint | BigQuery | Local | Soft-deleted |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {t} | `{e}` | {live:,} | {have:,} | {gone:,} |"
            for t, e, live, have, gone in sorted(verdicts[verdict], key=lambda v: -abs(v[2] - v[3]))
        ]
    text = "\n".join(lines) + "\n"
    OUT.write_text(text)
    print(text[: text.index("## ")] if "## " in text else text)
    for verdict in ("bq_less", "bq_only"):
        for t, e, live, have, _ in verdicts[verdict][:15]:
            print(f"  {verdict}: {t} / {e}: BigQuery {live:,} vs local {have:,}")
    return 1 if verdicts["bq_less"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
