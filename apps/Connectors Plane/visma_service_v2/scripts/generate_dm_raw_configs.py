#!/usr/bin/env python3
"""Generate a raw (un-normalized) endpoint config for every DataMart bulk root.

The goal is to land *everything* DataMart exposes, untouched, so it can be mapped in Dataform
later. The ERP-shaped normalizers are lossy by design (they drop DataMart-only fields), so each
root gets its own `dm_<root>` endpoint next to any ERP-shadow block that already uses it.

For each bulk root (a query root taking `lastId` + `pageSize`) it writes:

  config/endpoints/dm_<root>.json    source=datamart_graphql, key `id`, cursor
                                     `updatedInDataMartDateTime`, no normalizer
  config/queries/dm_<root>.graphql   the generated full-field query, with `includeDeleted`
                                     defaulting to true (the paginator never sends the variable,
                                     and the generated default would hide deletions)

Roots that DataMart serves under two names with identical rows are only ingested once (see
ALIASES). Existing files are left alone unless --force is given.

Usage:
  scripts/generate_dm_raw_configs.py --dry-run
  scripts/generate_dm_raw_configs.py
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INTROSPECTION = ROOT / "core/queries/_generated/datamart.introspection.json"

# root -> the root that is kept. Verified row-for-row (same ids, same fields, zero differing rows).
ALIASES: dict[str, str] = {
    "apInvoices": "supplierDocuments",
    "apInvoiceLines": "supplierDocumentLines",
    "apPaymentLines": "supplierPaymentLines",
    "apPayments": "supplierPayments",
    "salesOrderLines": "salesOrderLinesV2",
}

# Roots that cannot run as plain bulk pulls (required variables the paginator does not send).
NEEDS_VARIABLES: dict[str, str] = {
    "generalLedgerBalancesByPeriod": "requires $finPeriodId",
}

# Selections Visma cannot serve, dropped from the generated query: root -> nested fields. Asking
# for `warehouses.locations` fails the whole page with "Cannot return null for non-nullable
# field" (the same rows are in `warehouseLocations`, which has its own root).
EXCLUDED_SELECTIONS: dict[str, tuple[str, ...]] = {
    "warehouses": ("locations",),
}

HEADER = (
    "# Generated by scripts/generate_dm_raw_configs.py from\n"
    "# config/queries/datamart/{gen}.graphql.\n"
    "# includeDeleted defaults to true: the paginator never sends the variable, and the generated\n"
    "# default (false) would hide deletions from bronze. Deleted rows arrive with\n"
    "# deletedDatabaseRecord = true.\n"
)


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def unwrap(type_ref: dict) -> str:
    while type_ref.get("ofType"):
        type_ref = type_ref["ofType"]
    return type_ref["name"]


def bulk_roots() -> dict[str, tuple[str, set[str]]]:
    raw = json.loads(INTROSPECTION.read_text())
    schema = (raw.get("data") or raw)["__schema"]
    types = {t["name"]: t for t in schema["types"]}
    roots = {}
    for field in types["Query"]["fields"]:
        if {"lastId", "pageSize"} <= {a["name"] for a in field["args"]}:
            type_name = unwrap(field["type"])
            roots[field["name"]] = (type_name, {f["name"] for f in types[type_name]["fields"]})
    return roots


FALSE_DEFAULT = "$includeDeleted: Boolean! = false"
TRUE_DEFAULT = "$includeDeleted: Boolean! = true"


def with_deletions_included(query: str) -> tuple[str, str]:
    """Return (query, explanatory comment) so deleted rows are requested wherever possible."""
    if FALSE_DEFAULT in query:
        return query.replace(FALSE_DEFAULT, TRUE_DEFAULT), ""
    if TRUE_DEFAULT in query:
        return query, ""
    return query, (
        "# This root has no includeDeleted argument: DataMart does not expose deletions for it,\n"
        "# so removed rows simply stop appearing.\n"
    )


def drop_selection(query: str, field: str) -> str:
    """Remove the nested selection `field { ... }` (brace-matched) from a query."""
    lines, kept, depth, skipping = query.splitlines(keepends=True), [], 0, False
    for line in lines:
        if not skipping and line.strip() == f"{field} {{":
            skipping, depth = True, 1
            continue
        if skipping:
            depth += line.count("{") - line.count("}")
            skipping = depth > 0
            continue
        kept.append(line)
    return "".join(kept)


def config_for(root: str, type_name: str, fields: set[str]) -> dict:
    name = f"dm_{snake(root)}"
    validation = [f for f in ("id", "companyId", "updatedInDataMartDateTime") if f in fields]
    return {
        "endpoint_name": name,
        "bigquery_table": f"visma_{name}",
        "primary_key": "id",
        "source": "datamart_graphql",
        "enabled": True,
        "api_method": f"datamart.{root}",
        "modified_field": "updatedInDataMartDateTime",
        "merge_type": "upsert",
        "sync_pattern": "incremental_upsert",
        "validation_fields": validation,
        "notes": (
            f"Raw DataMart `{root}` ({type_name}), stored untouched for later Dataform mapping. "
            "No join_normalizer: every DataMart field is kept, unlike the lossy ERP-shaped "
            "shadow block some ERP endpoints carry. Deleted rows are included "
            "(deletedDatabaseRecord=true). Needs VSV2_AQUATIQ_DATAMART_COMPANY_ID."
        ),
        "datamart": {
            "ready": True,
            "query_file": f"config/queries/{name}.graphql",
            "root_field": root,
            "type_name": type_name,
            "cursor_field": "updatedInDataMartDateTime",
            "id_field": "id",
            "company_filter": True,
            "fallback_source": "datamart_graphql",
        },
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true", help="overwrite existing dm_* files")
    ap.add_argument("--skip", default="", help="comma-separated roots to leave out")
    args = ap.parse_args()
    skip = {s for s in args.skip.split(",") if s}

    created, kept, skipped = [], [], []
    for root, (type_name, fields) in sorted(bulk_roots().items()):
        if root in ALIASES:
            skipped.append(f"{root} (alias of {ALIASES[root]})")
            continue
        if root in NEEDS_VARIABLES:
            skipped.append(f"{root} ({NEEDS_VARIABLES[root]})")
            continue
        if root in skip:
            skipped.append(f"{root} (--skip)")
            continue
        cfg = config_for(root, type_name, fields)
        cfg_path = ROOT / "config/endpoints" / f"{cfg['endpoint_name']}.json"
        query_path = ROOT / cfg["datamart"]["query_file"]
        generated = ROOT / f"config/queries/datamart/{snake(root)}.graphql"
        if not generated.exists():
            skipped.append(f"{root} (no generated query {generated.name})")
            continue
        if cfg_path.exists() and not args.force:
            kept.append(cfg["endpoint_name"])
            continue
        text = generated.read_text()
        for excluded in EXCLUDED_SELECTIONS.get(root, ()):
            text = drop_selection(text, excluded)
        body, note = with_deletions_included(text)
        created.append(cfg["endpoint_name"])
        if not args.dry_run:
            query_path.write_text(HEADER.format(gen=snake(root)) + note + body)
            cfg_path.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")

    verb = "would create" if args.dry_run else "created"
    print(f"{verb} {len(created)}: {', '.join(created)}")
    print(f"already present {len(kept)}; skipped {len(skipped)}:")
    for item in skipped:
        print(f"  - {item}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
