"""DataMart GraphQL introspection — Phase 0 deliverable."""

from __future__ import annotations

import json
import time
from pathlib import Path

from graphql import get_introspection_query
from rich import print as rprint

from .._http import DatamartGraphQL, OAuth, VismaEnv

INTROSPECTION_QUERY = get_introspection_query()


def run(out_path: str) -> None:
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    json_path = out.with_suffix(".introspection.json")

    env = VismaEnv.from_env()
    rprint(f"[cyan]→[/cyan] introspecting {env.datamart_url} …")
    oauth = OAuth(env)
    gql = DatamartGraphQL(env, oauth)

    started = time.time()
    try:
        data = gql.execute(INTROSPECTION_QUERY)
    finally:
        gql.close()
        oauth.close()

    schema = data.get("__schema")
    if schema is None:
        raise RuntimeError("introspection returned no __schema")

    json_path.write_text(json.dumps(data, indent=2))
    rprint(f"[green]✓[/green] introspection JSON → {json_path}")

    sdl = _to_sdl(schema)
    out.write_text(sdl)
    rprint(f"[green]✓[/green] SDL → {out}")
    rprint(f"[dim]({time.time() - started:.1f}s, {len(schema.get('types', []))} types)[/dim]")


def list_companies() -> None:
    env = VismaEnv.from_env()
    oauth = OAuth(env)
    gql = DatamartGraphQL(env, oauth)
    probes = ("accounts", "branches", "customers", "locations")
    rprint("[cyan]→[/cyan] discovering companyIds from live query roots")
    try:
        rows: list[int] = []
        probe_field: str | None = None
        for root_field in probes:
            query = f"query DiscoverCompanyIds {{ {root_field}(pageSize: 100) {{ companyId }} }}"
            data = gql.execute(query)
            ids = sorted(
                {
                    row.get("companyId")
                    for row in (data.get(root_field) or [])
                    if row.get("companyId") is not None
                }
            )
            if ids:
                rows = ids
                probe_field = root_field
                break
    finally:
        gql.close()
        oauth.close()

    if not rows:
        rprint("[red]no companyIds returned — check OAuth scope, tenant, or ETL activation[/red]")
        return

    rprint(f"[green]✓[/green] {len(rows)} companyIds visible via [bold]{probe_field}[/bold]:")
    for company_id in rows:
        rprint(f"  {company_id}")
    rprint(
        "\n[yellow]next:[/yellow] set the matching id as "
        "[bold]VSV2_AQUATIQ_DATAMART_COMPANY_ID[/bold] in [bold].env[/bold]"
    )


def _to_sdl(schema: dict) -> str:
    """Serialize a `__schema` introspection payload to a minimal SDL.

    Not bit-exact to the GraphQL spec — sufficient for diff-friendly snapshots
    in CI. Skips scalars/directives, focuses on Object + Input + Enum types.
    """
    lines: list[str] = ["# Generated by vsv2-discover introspect", ""]
    types = sorted(schema.get("types", []), key=lambda t: t.get("name") or "")
    for t in types:
        name = t.get("name") or ""
        if not name or name.startswith("__"):
            continue
        kind = t.get("kind")
        if kind == "OBJECT":
            lines.append(f"type {name} {{")
            for f in t.get("fields") or []:
                lines.append(f"  {f['name']}: {_render_type_ref(f['type'])}")
            lines.append("}")
            lines.append("")
        elif kind == "INPUT_OBJECT":
            lines.append(f"input {name} {{")
            for f in t.get("inputFields") or []:
                lines.append(f"  {f['name']}: {_render_type_ref(f['type'])}")
            lines.append("}")
            lines.append("")
        elif kind == "ENUM":
            lines.append(f"enum {name} {{")
            for v in t.get("enumValues") or []:
                lines.append(f"  {v['name']}")
            lines.append("}")
            lines.append("")
    return "\n".join(lines)


def _render_type_ref(ref: dict) -> str:
    kind = ref.get("kind")
    if kind == "NON_NULL":
        return f"{_render_type_ref(ref['ofType'])}!"
    if kind == "LIST":
        return f"[{_render_type_ref(ref['ofType'])}]"
    return ref.get("name") or "Unknown"
