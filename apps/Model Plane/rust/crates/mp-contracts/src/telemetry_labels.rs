/// True when `name` is on the closed [`TRACE_FIELDS`] list.
#[must_use]
pub fn is_allowed_trace_field(name: &str) -> bool {
    TRACE_FIELDS.contains(&name)
}

/// One label key a metric macro used that is not on [`METRIC_LABELS`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DisallowedMetricLabel {
    /// The metric name literal (first macro argument), or empty when it is not a literal.
    pub metric: String,
    /// The offending label key.
    pub label: String,
}

/// True when `label` is on the closed list.
#[must_use]
pub fn is_allowed_metric_label(label: &str) -> bool {
    METRIC_LABELS.contains(&label)
}

/// Every `"key" =>` label of every `counter!`, `gauge!` and `histogram!` invocation in `source`
/// whose key is not on [`METRIC_LABELS`]. Comments are skipped; string literals are respected
/// when matching the macro's parentheses. An empty result means the file is clean.
#[must_use]
pub fn disallowed_metric_labels(source: &str) -> Vec<DisallowedMetricLabel> {
    let code = strip_line_comments(source);
    let bytes = code.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        let Some(open) = find_metric_macro(&code, i) else {
            break;
        };
        let end = matching_paren(bytes, open);
        let body = &code[open + 1..end];
        let metric = first_string_literal(body).unwrap_or_default();
        for label in label_keys(body) {
            if !is_allowed_metric_label(&label) {
                out.push(DisallowedMetricLabel {
                    metric: metric.clone(),
                    label,
                });
            }
        }
        i = end.max(open + 1);
    }
    out
}

/// Replace `// ...` comments (outside string literals) with spaces, keeping offsets stable.
fn strip_line_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut in_str = false;
    let mut chars = source.char_indices().peekable();
    while let Some((_, c)) = chars.next() {
        if in_str {
            out.push(c);
            if c == '\\' {
                if let Some((_, n)) = chars.next() {
                    out.push(n);
                }
            } else if c == '"' {
                in_str = false;
            }
            continue;
        }
        if c == '"' {
            in_str = true;
            out.push(c);
        } else if c == '/' && matches!(chars.peek(), Some((_, '/'))) {
            out.push(' ');
            for (_, n) in chars.by_ref() {
                if n == '\n' {
                    out.push('\n');
                    break;
                }
                out.push(' ');
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Byte offset of the `(` that opens the next `counter!`/`gauge!`/`histogram!` at or after `from`.
fn find_metric_macro(code: &str, from: usize) -> Option<usize> {
    let mut best: Option<usize> = None;
    for name in ["counter!", "gauge!", "histogram!"] {
        let mut start = from;
        while let Some(rel) = code[start..].find(name) {
            let at = start + rel;
            let before_ok = code[..at]
                .chars()
                .next_back()
                .is_none_or(|c| !(c.is_alphanumeric() || c == '_'));
            let rest = code[at + name.len()..].trim_start();
            if before_ok && rest.starts_with('(') {
                let open = code.len() - rest.len();
                best = Some(best.map_or(open, |b| b.min(open)));
                break;
            }
            start = at + name.len();
        }
    }
    best
}

/// Index of the `)` that closes the `(` at `open`, skipping string literals. Clamped to the end.
fn matching_paren(bytes: &[u8], open: usize) -> usize {
    let mut depth = 0usize;
    let mut in_str = false;
    let mut i = open;
    while i < bytes.len() {
        let b = bytes[i];
        if in_str {
            if b == b'\\' {
                i += 1;
            } else if b == b'"' {
                in_str = false;
            }
        } else if b == b'"' {
            in_str = true;
        } else if b == b'(' {
            depth += 1;
        } else if b == b')' {
            depth -= 1;
            if depth == 0 {
                return i;
            }
        }
        i += 1;
    }
    bytes.len()
}

fn first_string_literal(body: &str) -> Option<String> {
    let start = body.find('"')? + 1;
    let len = body[start..].find('"')?;
    Some(body[start..start + len].to_owned())
}

/// The `"key"` of every `"key" =>` in a macro body, in order.
fn label_keys(body: &str) -> Vec<String> {
    let mut keys = Vec::new();
    let mut rest = body;
    while let Some(q) = rest.find('"') {
        let after = &rest[q + 1..];
        let Some(close) = after.find('"') else { break };
        let lit = &after[..close];
        let tail = after[close + 1..].trim_start();
        if tail.starts_with("=>") {
            keys.push(lit.to_owned());
        }
        rest = &after[close + 1..];
    }
    keys
}

#[cfg(test)]
mod tests {
    use super::*;

    fn labels(source: &str) -> Vec<String> {
        disallowed_metric_labels(source)
            .into_iter()
            .map(|d| d.label)
            .collect()
    }

    #[test]
    fn allowed_labels_are_clean() {
        let src = r#"
            counter!("a_total", "method" => m, "status" => s, "route" => r).increment(1);
            gauge!("g", "outcome" => "ok").set(1.0);
            histogram!("h", "tool" => "bash").record(1.0);
        "#;
        assert!(disallowed_metric_labels(src).is_empty());
    }

    #[test]
    fn identifier_labels_are_rejected_with_the_metric_name() {
        let src = r#"counter!("runs_total", "thread_id" => id.to_string()).increment(1);"#;
        let found = disallowed_metric_labels(src);
        assert_eq!(
            found,
            vec![DisallowedMetricLabel {
                metric: "runs_total".to_owned(),
                label: "thread_id".to_owned(),
            }]
        );
    }

    #[test]
    fn the_raw_path_label_is_not_on_the_list() {
        assert!(!is_allowed_metric_label("path"));
        assert!(is_allowed_metric_label("route"));
        for id_like in ["thread_id", "run_id", "space_id", "org_id", "user_id"] {
            assert!(!is_allowed_metric_label(id_like), "{id_like}");
        }
    }

    #[test]
    fn list_has_no_duplicates() {
        let mut seen = std::collections::BTreeSet::new();
        for key in METRIC_LABELS {
            assert!(seen.insert(*key), "duplicate label {key}");
        }
    }

    #[test]
    fn comment_lines_are_ignored() {
        let src = "// counter!(\"x\", \"thread_id\" => id).increment(1);\n\
                   let y = 1; // histogram!(\"z\", \"run_id\" => id)\n";
        assert!(disallowed_metric_labels(src).is_empty());
    }

    #[test]
    fn slashes_inside_string_literals_are_not_comments() {
        let src = r#"counter!("http://x", "run_id" => id).increment(1);"#;
        assert_eq!(labels(src), vec!["run_id".to_owned()]);
    }

    #[test]
    fn multi_line_macros_are_scanned() {
        let src = "counter!(\n    \"multi_total\",\n    \"method\" => m,\n    \"space_id\" => s,\n    \"status\" => st\n)\n.increment(1);\n";
        let found = disallowed_metric_labels(src);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].label, "space_id");
        assert_eq!(found[0].metric, "multi_total");
    }

    #[test]
    fn the_metrics_path_form_is_scanned() {
        let src = r#"metrics::counter!("p_total", "thread_id" => id).increment(1);"#;
        assert_eq!(labels(src), vec!["thread_id".to_owned()]);
        let src = r#"metrics::histogram!("p_seconds", "run_id" => id).record(1.0);"#;
        assert_eq!(labels(src), vec!["run_id".to_owned()]);
    }

    #[test]
    fn a_non_literal_metric_name_still_checks_labels() {
        let src = r#"counter!(NAME, "thread_id" => id).increment(1);"#;
        let found = disallowed_metric_labels(src);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].label, "thread_id");
        // The first string literal in the body is the label key, not a metric name; the guard
        // still reports the key, which is what matters.
        assert!(found[0].metric == "thread_id" || found[0].metric.is_empty());
    }

    #[test]
    fn identifiers_that_merely_end_in_a_macro_name_are_not_macros() {
        let src = r#"my_counter!("x", "thread_id" => id);"#;
        assert!(disallowed_metric_labels(src).is_empty());
    }

    #[test]
    fn a_macro_name_without_a_call_is_not_scanned() {
        let src = r#"// use metrics::{counter, gauge};
            let counter_name = "counter!"; let _ = "thread_id" => 1;"#;
        assert!(disallowed_metric_labels(src).is_empty());
    }

    #[test]
    fn several_macros_in_one_file_are_all_checked() {
        let src = r#"
            counter!("a", "method" => m).increment(1);
            gauge!("b", "run_id" => r).set(1.0);
            histogram!("c", "thread_id" => t).record(1.0);
        "#;
        assert_eq!(labels(src), vec!["run_id".to_owned(), "thread_id".to_owned()]);
    }

    #[test]
    fn a_closing_paren_inside_a_string_does_not_end_the_macro() {
        let src = r#"counter!("a", "method" => ")", "run_id" => r).increment(1);"#;
        assert_eq!(labels(src), vec!["run_id".to_owned()]);
    }

    #[test]
    fn an_unterminated_macro_does_not_panic() {
        let _ = disallowed_metric_labels(r#"counter!("a", "run_id" => r"#);
    }
}
