"""Every checked-in Model Plane pb2 module imports and declares its proto file.

The model_plane/v1 bindings are generated by buf. This guards the checked-in
copies: a broken module fails to import, and a module that lacks a top-level
message or enum its .proto declares (a stale copy) fails the proto comparison.
"""

import importlib
import re
from pathlib import Path

import pytest

GEN_DIR = Path(__file__).resolve().parents[1] / "src" / "mp_events" / "_gen" / "model_plane" / "v1"
PROTO_DIR = Path(__file__).resolve().parents[3] / "proto" / "model_plane" / "v1"
MODULES = sorted(p.name.removesuffix(".py") for p in GEN_DIR.glob("*_pb2.py"))


def test_gen_dir_has_modules():
    assert MODULES, f"no *_pb2.py modules under {GEN_DIR}"


@pytest.mark.parametrize("module", MODULES)
def test_pb2_module_imports_and_declares_its_proto(module):
    mod = importlib.import_module(f"mp_events._gen.model_plane.v1.{module}")
    base = module.removesuffix("_pb2")
    assert mod.DESCRIPTOR.package == "model_plane.v1"
    assert mod.DESCRIPTOR.name == f"model_plane/v1/{base}.proto"


@pytest.mark.skipif(not PROTO_DIR.is_dir(), reason="proto sources not alongside this package")
@pytest.mark.parametrize("module", MODULES)
def test_pb2_module_has_every_top_level_type_its_proto_declares(module):
    mod = importlib.import_module(f"mp_events._gen.model_plane.v1.{module}")
    base = module.removesuffix("_pb2")
    text = (PROTO_DIR / f"{base}.proto").read_text(encoding="utf-8")
    declared = {m.group(2): m.group(1) for m in re.finditer(r"^(message|enum)\s+(\w+)", text, re.MULTILINE)}
    have_msgs = set(mod.DESCRIPTOR.message_types_by_name)
    have_enums = set(mod.DESCRIPTOR.enum_types_by_name)
    missing = sorted(
        name
        for name, kind in declared.items()
        if name not in (have_msgs if kind == "message" else have_enums)
    )
    assert not missing, f"{module} is stale against {base}.proto, missing: {missing}"
