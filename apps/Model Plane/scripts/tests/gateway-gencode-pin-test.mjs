// Pins the checked-in TypeScript gencode for the Model Plane gateway to the proto
// it is generated from, and to the plugin versions named in proto/buf.gen.yaml.
//
// Static checks only (no buf, no network), so they run on every proto change:
//   1. buf.gen.yaml pins buf.build/bufbuild/es and buf.build/bufbuild/connect-es
//      to exact versions, and the headers of gateway_pb.ts and gateway_connect.ts
//      name those same versions.
//   2. The messages and rpcs that gateway.proto declares are the ones
//      gateway_pb.ts documents, and every field the proto declares (name and
//      number) has exactly one "@generated from field" line, with no extra field.
//   3. The first non-empty line of every leading comment in gateway.proto
//      (message, field and rpc) appears in gateway_pb.ts, so the JSDoc blocks
//      are not stale.
//   4. The EP-11 S3 Skill version and digest fields and the W4-PL-1 Plugin source
//      fields are generated with their proto field numbers.
//
// A failure means gateway_pb.ts or gateway_connect.ts was not regenerated after
// gateway.proto or buf.gen.yaml changed. Regenerate only those two files: from
// apps/Model Plane/proto, run `buf generate --template <tmp.yaml> --path
// model_plane/v1/gateway.proto`, where <tmp.yaml> names the pinned remotes with
// the same managed mode and opt values as buf.gen.yaml and writes to a temporary
// directory. Then copy the two generated files over the checked-in ones. Do not
// rerun the full buf.gen.yaml without reviewing the diff of every other gen file.
//
// GATEWAY_PB_TS and GATEWAY_CONNECT_TS override the checked-in paths, so the same
// assertions can be run against an earlier copy of the file.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..", "..", "..");
const protoDir = resolve(repo, "apps", "Model Plane", "proto");
const protoPath = resolve(protoDir, "model_plane", "v1", "gateway.proto");
const bufGenPath = resolve(protoDir, "buf.gen.yaml");
const genDir = resolve(
  repo,
  "apps",
  "Frontend Plane",
  "verevon",
  "src",
  "lib",
  "model-plane",
  "gen",
  "model_plane",
  "v1",
);
const pbPath = process.env.GATEWAY_PB_TS || resolve(genDir, "gateway_pb.ts");
const connectPath =
  process.env.GATEWAY_CONNECT_TS || resolve(genDir, "gateway_connect.ts");

const read = (file) => readFileSync(file, "utf8");

// Remote plugins as written in buf.gen.yaml, for example
// "buf.build/bufbuild/es:v2.16.0".
const remotes = [...read(bufGenPath).matchAll(/^\s*-\s*remote:\s*(\S+)\s*$/gm)].map(
  (m) => m[1],
);

function pinnedVersion(plugin) {
  const hits = remotes.filter((remote) => remote.split(":")[0] === plugin);
  assert.equal(hits.length, 1, `${plugin} must be listed once in buf.gen.yaml`);
  const m = hits[0].match(/:v(\d+\.\d+\.\d+)$/);
  assert.ok(m, `${hits[0]} must pin an exact version, for example ${plugin}:v2.16.0`);
  return m[1];
}

function headerVersion(text, generator) {
  const first = text.split(/\r?\n/, 1)[0];
  const m = first.match(
    new RegExp(`^// @generated by ${generator} v(\\d+\\.\\d+\\.\\d+) `),
  );
  assert.ok(m, `first line must be the ${generator} header, got: ${first}`);
  return m[1];
}

// Declarations of gateway.proto as the generator sees them. Leading comments are
// the adjacent "//" lines directly above a declaration, with no blank line between.
const DECL = /^(message|rpc)\s+(\w+)\b/;
const FIELD =
  /^(?:repeated\s+|optional\s+)?(?:map<[^>]+>|[A-Za-z_][\w.]*)\s+([a-z][a-z0-9_]*)\s*=\s*(\d+)\s*;/;

function parseProto(text) {
  const decls = [];
  const fields = [];
  let comment = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith("//")) {
      comment.push(line.slice(2).trim());
      continue;
    }
    const doc = comment.find((c) => c !== "") ?? null;
    comment = [];
    if (line === "") continue;
    const decl = line.match(DECL);
    if (decl) {
      decls.push({ kind: decl[1], name: decl[2], doc });
      continue;
    }
    const field = line.match(FIELD);
    if (field) {
      fields.push({ name: field[1], number: Number(field[2]), doc });
    }
  }
  return { decls, fields };
}

const sorted = (values) => [...values].sort();

test("buf.gen.yaml pins the TypeScript plugins and the headers name those versions", () => {
  const esVersion = pinnedVersion("buf.build/bufbuild/es");
  const connectVersion = pinnedVersion("buf.build/bufbuild/connect-es");
  assert.equal(headerVersion(read(pbPath), "protoc-gen-es"), esVersion);
  assert.equal(
    headerVersion(read(connectPath), "protoc-gen-connect-es"),
    connectVersion,
  );
});

test("gateway_pb.ts documents exactly the messages and rpcs gateway.proto declares", () => {
  const { decls } = parseProto(read(protoPath));
  const pbText = read(pbPath);
  const genMessages = [...pbText.matchAll(/@generated from message \S+\.(\w+)\s*$/gm)].map(
    (m) => m[1],
  );
  const genRpcs = [...pbText.matchAll(/@generated from rpc \S+\.(\w+)\s*$/gm)].map(
    (m) => m[1],
  );
  const protoMessages = decls.filter((d) => d.kind === "message").map((d) => d.name);
  const protoRpcs = decls.filter((d) => d.kind === "rpc").map((d) => d.name);
  assert.deepEqual(sorted(genMessages), sorted(protoMessages));
  assert.deepEqual(sorted(genRpcs), sorted(protoRpcs));
});

test("gateway_pb.ts declares every field of gateway.proto with its number, and no other", () => {
  const { fields } = parseProto(read(protoPath));
  const genFields = [
    ...read(pbPath).matchAll(/@generated from field: .*? ([a-z][a-z0-9_]*) = (\d+);/g),
  ].map((m) => `${m[1]}=${m[2]}`);
  const protoFields = fields.map((f) => `${f.name}=${f.number}`);
  assert.ok(protoFields.length > 0, "the proto parse found no fields");
  const missing = protoFields.filter((f) => !genFields.includes(f));
  const extra = genFields.filter((f) => !protoFields.includes(f));
  assert.deepEqual(
    { missing, extra },
    { missing: [], extra: [] },
    "gateway_pb.ts is out of date with gateway.proto",
  );
  assert.equal(genFields.length, protoFields.length);
});

test("the leading comment of every message, field and rpc is in gateway_pb.ts", () => {
  const { decls, fields } = parseProto(read(protoPath));
  const pbText = read(pbPath);
  const documented = [...decls, ...fields].filter((d) => d.doc !== null);
  assert.ok(documented.length > 0, "the proto parse found no leading comments");
  const stale = documented
    .filter((d) => !pbText.includes(d.doc))
    .map((d) => `${d.name}: ${d.doc}`);
  assert.deepEqual(
    stale.slice(0, 10),
    [],
    `${stale.length} leading comments are missing from gateway_pb.ts`,
  );
});

test("EP-11 S3 Skill version and digest and W4-PL-1 Plugin source fields are generated", () => {
  const text = read(pbPath);
  for (const declaration of [
    "@generated from field: int32 version = 7;",
    "@generated from field: string digest = 8;",
    "@generated from field: string source_kind = 9;",
    "@generated from field: string source_pin = 10;",
    "@generated from field: string source_ref = 11;",
  ]) {
    assert.ok(text.includes(declaration), `gateway_pb.ts lacks: ${declaration}`);
  }
  assert.match(text, /^  sourceKind: string;$/m);
  assert.match(text, /^  digest: string;$/m);
});
