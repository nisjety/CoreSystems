export function useAuthCopy() {
  const { currentLocale } = useLanguageSwitch();
  const locale: AuthLocale = currentLocale === "en" ? "en" : "nb";
  return { locale, copy: AUTH_COPY[locale] };
}

export function formatAuthText(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (out, [key, value]) => out.replace(new RegExp(`{{\\s*${key}\\s*}}`, "g"), String(value)),
    template,
  );
}
