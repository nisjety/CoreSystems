export function useOnboardingCopy() {
  const { currentLocale } = useLanguageSwitch()
  const locale: OnboardingLocale = currentLocale === 'en' ? 'en' : 'nb'

  return {
    locale,
    copy: ONBOARDING_COPY[locale],
    formatNumber: (value: number) => formatOnboardingNumber(value, locale),
  }
}

export function formatOnboardingNumber(
  value: number,
  locale: OnboardingLocale,
): string {
  return value.toLocaleString(locale === 'nb' ? 'nb-NO' : 'en-US')
}

export function formatOnboardingText(
  template: string,
  values: Record<string, string | number>,
): string {
  return Object.entries(values).reduce(
    (out, [key, value]) =>
      out.replace(new RegExp(`{{\\s*${key}\\s*}}`, 'g'), String(value)),
    template,
  )
}

export function onboardingStepLabel(
  step: OnboardingStep,
  locale: OnboardingLocale,
): string {
  return ONBOARDING_COPY[locale].shared.stepLabels[step]
}

export function onboardingPlanName(
  id: OnboardingPlanId,
  locale: OnboardingLocale,
): string {
  return ONBOARDING_COPY[locale].paywall.plans[id].name
}
