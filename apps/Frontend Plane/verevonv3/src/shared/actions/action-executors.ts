import type { ActionId } from '@/shared/actions/action-registry'

/**
 * Who runs each registered action (O-26, D-f09-5): one exhaustive row per id, in the shape model-access.ts uses, so an
 * id added to the registry without a row fails `pnpm typecheck`.
 *
 * - `gateway`: the browser sends the id to POST /api/v1/actions/execute, and a named owner dispatcher runs it.
 * - `client`: the browser runs it on `clientRoute` (a REST path with {placeholders}, or `ui:<surface>` for an action
 *   that only changes what the page shows). The execute endpoint refuses it with `client_executed` and names that route.
 * - `owner_not_wired`: the execute endpoint answers 501, because the owner executor for the id is not built yet.
 *
 * The registry descriptor carries the same answer in its `executor` field, and action-registry.test.ts checks that the
 * two agree. action-surface-contract.test.mjs re-derives each id's arm kind from handlers.rs and checks it against this
 * map, so a mismatch names the id. This map is a sibling file, so model-access.ts and the admission golden do not move.
 */
