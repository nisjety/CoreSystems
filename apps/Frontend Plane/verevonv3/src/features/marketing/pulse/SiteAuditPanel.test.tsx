import { cleanup, fireEvent, render, screen, waitFor } from '@solidjs/testing-library'
import { createSignal } from 'solid-js'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { SiteAuditPanel } from './SiteAuditPanel'
vi.mock('@/shared/i18n', () => ({ useI18n: () => ({ tr: (_no: string, en: string) => en, locale: () => 'en' }), localeDateTime: () => 'en-GB' }))
const context = { websiteId: `web_${'1'.repeat(32)}`, site: 'https://triodelab.no/', websiteRevision: 7 }
const idle = { ...context, id: '', source: 'quarry_capture', ruleVersion: 'bounded_rules_v1', status: 'idle', limit: 10, partial: true, startedAt: '', completedAt: '', pages: [], findings: [], history: [] }
const auditId = `audit_${'3'.repeat(32)}`
const page = { url: 'https://www.triodelab.no/', finalUrl: 'https://www.triodelab.no/', status: 'checked', httpStatus: 200, title: '', description: '', canonical: '', observedAt: '2026-10-22T12:00:00Z', runId: `run_0${'1'.repeat(25)}`, fingerprint: `blake3:${'a'.repeat(64)}`, links: [], checks: [{ ruleId: 'missing_title_signal', status: 'failed' }] }
const finding = { id: `finding_${'2'.repeat(32)}`, ruleId: 'missing_title_signal', severity: 'warning', pageUrl: page.url, observedAt: page.observedAt, runId: page.runId, fingerprint: page.fingerprint, relatedUrls: [`${context.site}related`] }
const complete = { ...idle, id: auditId, status: 'complete', startedAt: '2026-10-22T11:59:00Z', completedAt: '2026-10-22T12:01:00Z', pages: [page], findings: [finding] }
const running = { ...idle, id: auditId, status: 'running', startedAt: complete.startedAt }
const savedWork = { websiteId: context.websiteId, site: context.site, tasks: [{ id: `task_${'4'.repeat(32)}`, websiteId: context.websiteId, site: context.site, revision: 1, status: 'todo', createdAt: complete.completedAt, updatedAt: complete.completedAt, evidence: { kind: 'site_audit_finding', key: finding.ruleId, observedAt: finding.observedAt, auditId, findingId: finding.id, pageUrl: finding.pageUrl, severity: finding.severity, runId: finding.runId, fingerprint: finding.fingerprint, relatedUrls: finding.relatedUrls } }], activity: [], summary: { open: 1, inProgress: 0, done: 0, dismissed: 0, total: 1, completionPercent: 0 } }
const response = (data: unknown) => new Response(JSON.stringify({ data }))
const mount = (onWorkSaved = vi.fn(), onSettled = vi.fn()) => render(() => <SiteAuditPanel {...context} revision={7} onWorkSaved={onWorkSaved} onSettled={onSettled} />)
describe('site audit panel', () => {
 afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.useRealTimers() })
 it('reads saved status on mount and only runs after an explicit action', async () => {
  const fetcher = vi.fn<(input: RequestInfo | URL, init?: RequestInit) => Promise<Response>>(async () => new Response(JSON.stringify({ data: idle }))); vi.stubGlobal('fetch', fetcher)
  render(() => <SiteAuditPanel {...context} revision={7} onWorkSaved={() => undefined} />)
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(1))
  await waitFor(() => expect((screen.getByRole('button', { name: 'Run site audit' }) as HTMLButtonElement).disabled).toBe(false))
  expect(fetcher.mock.calls[0]?.[1]).toMatchObject({ method: 'GET' })
  await fireEvent.click(screen.getByRole('button', { name: 'Run site audit' }))
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
  expect(fetcher.mock.calls[1]?.[1]).toMatchObject({ method: 'POST', body: JSON.stringify(context) })
  expect(screen.getByText(/not an exhaustive/i)).toBeTruthy()
 })
 it('aborts requests and clears previous evidence when the site changes', async () => {
  const fetcher = vi.fn<(input: RequestInfo | URL, init?: RequestInit) => Promise<Response>>(() => new Promise<Response>(() => undefined)); vi.stubGlobal('fetch', fetcher)
  const [site, setSite] = createSignal(context.site)
  render(() => <SiteAuditPanel site={site()} websiteId={context.websiteId} revision={7} onWorkSaved={() => undefined} />)
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(1))
  const signal = fetcher.mock.calls[0]?.[1]?.signal
  setSite('https://agenci.no/')
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
  expect(signal?.aborted).toBe(true)
 })
 it('saves the selected server finding identity, not rendered metrics or submitted page evidence', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(response(complete)).mockResolvedValueOnce(response(savedWork))
  vi.stubGlobal('fetch', fetcher)
  const onWorkSaved = vi.fn(); mount(onWorkSaved)
  const save = await screen.findByRole('button', { name: 'Save as task' })
  expect(screen.getByText('Missing page title')).toBeTruthy()
  expect(screen.getByText(finding.relatedUrls[0]!)).toBeTruthy()
  expect(fetcher).toHaveBeenCalledTimes(1)
  fireEvent.click(save)
  await waitFor(() => expect(onWorkSaved).toHaveBeenCalledOnce())
  expect(fetcher.mock.calls[1]?.[0]).toBe('/api/v1/visibility/work/audit')
  expect(fetcher.mock.calls[1]?.[1]).toMatchObject({ method: 'POST', credentials: 'include', body: JSON.stringify({ ...context, auditId, findingId: finding.id }) })
  expect(screen.getByText('Finding saved to the work queue with source evidence.')).toBeTruthy()
  expect((save as HTMLButtonElement).disabled).toBe(false)
 })
 it('loads retained history by its pinned receipt ID without starting another audit', async () => {
  const olderId = `audit_${'5'.repeat(32)}`
  const history = [{ id: olderId, status: 'complete', startedAt: complete.startedAt, completedAt: complete.completedAt, pageCount: 1, findingCount: 1 }]
  const fetcher = vi.fn().mockResolvedValueOnce(response({ ...complete, history })).mockResolvedValueOnce(response({ ...complete, id: olderId, history }))
  vi.stubGlobal('fetch', fetcher); mount()
  const receipt = await screen.findByRole('button', { name: /1 pages · 1 findings/ })
  fireEvent.click(receipt)
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
  expect(fetcher.mock.calls[1]?.[0]).toContain(`auditId=${olderId}`)
  expect(fetcher.mock.calls[1]?.[1]).toMatchObject({ method: 'GET' })
  await waitFor(() => expect((screen.getByRole('button', { name: 'Refresh audit status' }) as HTMLButtonElement).disabled).toBe(false))
  expect(screen.queryByRole('alert')).toBeNull()
 })
 it('reports read failures and retries only a status read after an explicit refresh', async () => {
  const fetcher = vi.fn().mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce(response({ ...idle, status: 'failed', reason: 'not_configured' }))
  vi.stubGlobal('fetch', fetcher); mount()
  expect((await screen.findByRole('alert')).textContent).toContain('Refresh status before starting again')
  fireEvent.click(screen.getByRole('button', { name: 'Refresh audit status' }))
  await screen.findByText(/Source status: not_configured/)
  expect(screen.queryByRole('alert')).toBeNull()
  expect(fetcher.mock.calls.every((call) => call[1]?.method === 'GET')).toBe(true)
  expect(screen.getByText(/Missing evidence is not a passing result/)).toBeTruthy()
 })
 it('does not claim an ambiguous save failed definitively or invent a task after network failure', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(response(complete)).mockRejectedValueOnce(new Error('connection lost'))
  vi.stubGlobal('fetch', fetcher)
  const onWorkSaved = vi.fn(); mount(onWorkSaved)
  fireEvent.click(await screen.findByRole('button', { name: 'Save as task' }))
  const alert = await screen.findByRole('alert')
  expect(alert.textContent).toContain('The save result could not be confirmed')
  expect(alert.textContent).not.toContain('was not saved')
  expect(onWorkSaved).not.toHaveBeenCalled()
  expect(screen.getByRole('button', { name: 'Save as task' })).toBeTruthy()
 })
 it('polls the running receipt using GET and stops after a completed result', async () => {
  vi.useFakeTimers()
  const fetcher = vi.fn().mockResolvedValueOnce(response(running)).mockResolvedValueOnce(response(complete))
  vi.stubGlobal('fetch', fetcher)
  const view = mount()
  await vi.advanceTimersByTimeAsync(0)
  expect(view.container.textContent).toContain('Audit running')
  expect((screen.getByRole('button', { name: 'Run site audit' }) as HTMLButtonElement).disabled).toBe(true)
  await vi.advanceTimersByTimeAsync(3000)
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(fetcher.mock.calls[1]?.[0]).toContain(`auditId=${auditId}`)
  expect(fetcher.mock.calls[1]?.[1]).toMatchObject({ method: 'GET' })
  expect(view.container.textContent).toContain('1/1 pages checked')
  await vi.advanceTimersByTimeAsync(30_000)
  expect(fetcher).toHaveBeenCalledTimes(2)
 })
 it('bounds status polling and clears scheduled reads when unmounted', async () => {
  vi.useFakeTimers(); vi.setSystemTime(new Date('2026-10-22T12:00:00Z'))
  const fetcher = vi.fn().mockImplementation(() => Promise.resolve(response(running)))
  vi.stubGlobal('fetch', fetcher)
  const view = mount(); await vi.advanceTimersByTimeAsync(0)
  vi.setSystemTime(new Date('2026-10-22T12:15:08Z'))
  await vi.advanceTimersByTimeAsync(3000)
  expect(view.container.textContent).toContain('Status polling stopped')
  expect(fetcher).toHaveBeenCalledTimes(2)
  await vi.advanceTimersByTimeAsync(30_000)
  expect(fetcher).toHaveBeenCalledTimes(2)
  fireEvent.click(screen.getByRole('button', { name: 'Refresh audit status' }))
  await vi.advanceTimersByTimeAsync(0)
  expect(fetcher).toHaveBeenCalledTimes(3)
  const signal = fetcher.mock.calls[2]?.[1]?.signal
  view.unmount()
  expect(signal.aborted).toBe(true)
  await vi.advanceTimersByTimeAsync(30_000)
  expect(fetcher).toHaveBeenCalledTimes(3)
 })
 it('ignores a saved-work response after the user changes website context', async () => {
  let resolveSave: ((value: Response) => void) | undefined
  const otherSite = 'https://agenci.no/'
  const fetcher = vi.fn().mockResolvedValueOnce(response(complete)).mockImplementationOnce(() => new Promise<Response>((resolve) => { resolveSave = resolve })).mockResolvedValueOnce(response({ ...idle, site: otherSite }))
  vi.stubGlobal('fetch', fetcher)
  const onWorkSaved = vi.fn(), [site, setSite] = createSignal(context.site)
  const view = render(() => <SiteAuditPanel site={site()} websiteId={context.websiteId} revision={7} onWorkSaved={onWorkSaved} />)
  fireEvent.click(await screen.findByRole('button', { name: 'Save as task' }))
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
  const signal = fetcher.mock.calls[1]?.[1]?.signal
  setSite(otherSite)
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(3))
  expect(signal.aborted).toBe(true)
  resolveSave?.(response(savedWork))
  await new Promise((resolve) => setTimeout(resolve, 0))
  expect(onWorkSaved).not.toHaveBeenCalled()
  expect(view.container.textContent).not.toContain('Finding saved')
  expect(view.container.textContent).not.toContain(finding.pageUrl)
 })
 it.each(['complete', 'failed'] as const)('notifies once after an explicitly started audit settles as %s, never for initial saved results', async (status) => {
  vi.useFakeTimers()
  const settled = status === 'complete' ? complete : { ...complete, status: 'failed', reason: 'source_unavailable', pages: [], findings: [] }
  const fetcher = vi.fn().mockResolvedValueOnce(response(complete)).mockResolvedValueOnce(response(running)).mockResolvedValueOnce(response(settled)).mockResolvedValueOnce(response(settled))
  vi.stubGlobal('fetch', fetcher)
  const onSettled = vi.fn(); mount(vi.fn(), onSettled)
  await vi.advanceTimersByTimeAsync(0)
  expect(onSettled).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Run site audit' }))
  await vi.advanceTimersByTimeAsync(0)
  expect(onSettled).not.toHaveBeenCalled()
  await vi.advanceTimersByTimeAsync(3000)
  expect(onSettled).toHaveBeenCalledOnce()
  fireEvent.click(screen.getByRole('button', { name: 'Refresh audit status' }))
  await vi.advanceTimersByTimeAsync(0)
  expect(onSettled).toHaveBeenCalledOnce()
  expect(fetcher.mock.calls.slice(2).every((call) => call[1]?.method === 'GET')).toBe(true)
 })
 it('suppresses settled notifications from an aborted previous-site polling response', async () => {
  vi.useFakeTimers()
  let resolveOld: ((value: Response) => void) | undefined
  const fetcher = vi.fn().mockResolvedValueOnce(response(running)).mockImplementationOnce(() => new Promise<Response>((resolve) => { resolveOld = resolve })).mockResolvedValueOnce(response({ ...idle, site: 'https://agenci.no/' }))
  vi.stubGlobal('fetch', fetcher)
  const onSettled = vi.fn(), [site, setSite] = createSignal(context.site)
  render(() => <SiteAuditPanel site={site()} websiteId={context.websiteId} revision={7} onWorkSaved={() => undefined} onSettled={onSettled} />)
  await vi.advanceTimersByTimeAsync(3000)
  expect(fetcher).toHaveBeenCalledTimes(2)
  setSite('https://agenci.no/')
  await vi.advanceTimersByTimeAsync(0)
  expect(fetcher.mock.calls[1]?.[1]?.signal.aborted).toBe(true)
  resolveOld?.(response(complete)); await vi.advanceTimersByTimeAsync(0)
  expect(onSettled).not.toHaveBeenCalled()
 })
})
